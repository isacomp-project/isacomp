#!/usr/bin/env python3
"""Generate Verilog from SHA ILA with child (hierarchical)."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent.parent))

from frontends.ila.ila_parser_real import RealILAParser
from frontends.ila.accelerator_verilog_generator import ILAVerilogGenerator

def main():
    print("=" * 70)
    print("SHA Hierarchical Verilog Generation")
    print("=" * 70)

    json_file = 'test_data/sha_full.json'  # Generated by generate_sha_full_json.py
    output_file = 'sha_full_inlined.v'

    print(f"\n1. Loading {json_file}...")
    with open(json_file, 'r') as f:
        ila_data = json.load(f)

    print(f"   Loaded: {len(ila_data.get('a', []))} expressions")
    print(f"   Child ILAs: {len(ila_data.get('c', []))}") 

    print("\n2. Parsing with accelerator mode...")
    parser = RealILAParser()
    graph = parser.parse_json(ila_data, skip_optimizations=False, ila_type='accelerator')
    print(f"   Parsed: {len(graph.nodes)} nodes, {len(graph.edges)} edges")

    print("\n3. Generating Verilog...")
    generator = ILAVerilogGenerator(graph, module_name='sha_full')
    verilog_code = generator.generate()
    print(f"   Generated: {len(verilog_code)} chars, {verilog_code.count(chr(10))} lines")

    print(f"\n4. Writing to {output_file}...")
    with open(output_file, 'w') as f:
        f.write(verilog_code)
    print(f"   ✓ Written")

    print("\n" + "=" * 70)
    print("✓ SUCCESS: SHA hierarchical Verilog generation complete")
    print("=" * 70)

    return True


if __name__ == '__main__':
    try:
        success = main()
        sys.exit(0 if success else 1)
    except Exception as e:
        print(f"\n✗ ERROR: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)
