#!/usr/bin/env python3
"""
Memory Externalization Optimization

This optimization marks internal memory (like dmem, imem, rf, umem) for externalization.
The Verilog generator then uses the existing graph structure (which already has address
muxes, enable ORs, etc. from the graph merger) to generate external ports.

Multi-Port Support:
  When a memory has multiple access points (e.g., umem[pc] for instruction fetch and
  umem[ea] for data access), separate external ports are generated for each:
    - umem_pc_read_req_addr, umem_pc_read_resp_data (instruction fetch port)
    - umem_ea_read_req_addr, umem_ea_read_resp_data (data read port)
    - umem_ea_write_req_addr, umem_ea_write_req_data (data write port)

  This allows the SoC to implement separate memory interfaces (e.g., Harvard-style
  instruction and data buses) even for unified memory ISA definitions.

Port naming convention (generated by Verilog generator) - Valid-Ready Handshake Protocol:
  For each memory port {mem}_{port} (e.g., umem_pc, umem_ea):

  Read Request (outputs):
    {mem}_{port}_read_req_addr   - Address for read request
    {mem}_{port}_read_req_valid  - Request is valid (master -> slave)
  Read Response (inputs):
    {mem}_{port}_read_resp_data  - Data returned from memory
    {mem}_{port}_read_resp_ready - Response is ready (slave -> master)
  Write Request (outputs):
    {mem}_{port}_write_req_addr  - Address for write request
    {mem}_{port}_write_req_data  - Data to write
    {mem}_{port}_write_req_we    - Byte write enables (one bit per byte)
    {mem}_{port}_write_req_valid - Request is valid (master -> slave)
  Write Response (inputs):
    {mem}_{port}_write_resp_ready - Write complete acknowledgment (slave -> master)

Stalling Integration:
  - When {mem}_{port}_read_req_valid is asserted but {mem}_{port}_read_resp_ready is low,
    the processor stalls waiting for the response.
  - When {mem}_{port}_write_req_valid is asserted but {mem}_{port}_write_resp_ready is low,
    the processor stalls waiting for write acknowledgment.
  - These stall conditions integrate with the existing pipeline stall controller.

This protocol is compatible with AXI-Lite and other valid-ready based bus protocols
with simple adapter logic.
"""

from typing import Dict, List, Optional, Set
from core.resource_graph import ResourceGraph, Node, Edge


class MemoryExternalizationSpec:
    """Specification for externalizing a memory."""

    def __init__(self, memory_name: str, create_read_port: bool = True,
                 create_write_port: bool = True, variable_latency: bool = False):
        """
        Args:
            memory_name: Name of the memory to externalize (e.g., 'dmem', 'imem', 'rf', 'umem')
            create_read_port: Whether to create external read port
            create_write_port: Whether to create external write port
            variable_latency: Use valid-ready handshake protocol for variable latency memory
                              (required for AXI compatibility). If False, uses simple enable
                              signals suitable for single-cycle or fixed-latency memory.
        """
        self.memory_name = memory_name
        self.create_read_port = create_read_port
        self.create_write_port = create_write_port
        self.variable_latency = variable_latency


def apply_memory_externalization(graph: ResourceGraph, spec: MemoryExternalizationSpec) -> bool:
    """
    Mark a memory for externalization.

    This marks the memory node as externalized. The Verilog generator
    will use the existing graph structure (address muxes, enable ORs, data muxes)
    to generate the appropriate external ports with valid-ready handshake.

    Args:
        graph: Resource graph to modify
        spec: Specification for memory externalization

    Returns:
        True if successful, False otherwise
    """
    memory_name = spec.memory_name

    # Find the memory node
    memory_node = None
    for node in graph.nodes.values():
        if node.data and node.data.get('name') == memory_name:
            if node.data.get('is_memory', False):
                memory_node = node
                break

    if not memory_node:
        print(f"Error: Memory '{memory_name}' not found in graph")
        return False

    # Get memory properties for logging
    bit_width = memory_node.data.get('bit_width', 32)
    addr_width = memory_node.data.get('array_depth', 10)
    memory_latency = memory_node.latency if hasattr(memory_node, 'latency') else 0
    variable_latency = memory_node.variable_latency if hasattr(memory_node, 'variable_latency') else False

    print(f"Marking memory '{memory_name}' for externalization:")
    print(f"  Data width: {bit_width} bits")
    print(f"  Address width: {addr_width} bits")
    print(f"  Latency: {memory_latency} cycles" + (" (variable)" if variable_latency else ""))
    print(f"  Protocol: {'Valid-Ready Handshake' if spec.variable_latency else 'Simple Enable'}")

    # Mark the memory node as externalized
    memory_node.data['externalized'] = True
    memory_node.data['externalize_read'] = spec.create_read_port
    memory_node.data['externalize_write'] = spec.create_write_port
    memory_node.data['use_valid_ready'] = spec.variable_latency

    # For variable latency memory, mark as variable latency to enable stalling
    if spec.variable_latency:
        memory_node.variable_latency = True
        memory_node.data['memory_variable_latency'] = True

    print(f"  Read port: {'enabled' if spec.create_read_port else 'disabled'}")
    print(f"  Write port: {'enabled' if spec.create_write_port else 'disabled'}")

    # Create combined byte enable mux for write ports with per-instruction byte enables
    if spec.create_write_port:
        _create_combined_byte_enable(graph, memory_name)

    print(f"Successfully marked memory '{memory_name}' for externalization")

    return True


def _create_combined_byte_enable(graph: ResourceGraph, memory_name: str) -> Optional[str]:
    """Create combined byte enable mux nodes for each write port of an externalized memory.

    Finds write port nodes, checks for per-instruction byte enables, and creates
    a priority mux for each port that selects the appropriate byte enable based on
    which instruction is active. The combined byte enable node ID is stored on each
    write port for the Verilog generator to use.

    Args:
        graph: Resource graph to modify
        memory_name: Name of the memory

    Returns:
        The last combined byte enable node ID created, or None if no byte enables found
    """
    # Find write port node(s) for this memory
    write_port_nodes = []
    for node in graph.nodes.values():
        if node.data.get('type') == 'memory_write_port':
            # Check if this write port is for our memory
            for edge in node.outgoing_edges:
                if edge.data.get('type') == 'memory_write':
                    target = edge.target
                    if target.data.get('name') == memory_name or target.id == memory_name:
                        write_port_nodes.append(node)
                        break

    if not write_port_nodes:
        return None

    last_combined_be_id = None

    for write_port_node in write_port_nodes:
        store_byte_enables = write_port_node.data.get('store_byte_enables', {})
        if not store_byte_enables:
            continue

        print(f"  Creating combined byte enable for {write_port_node.id}")
        print(f"    Per-instruction byte enables: {store_byte_enables}")

        # Get instruction enable signals - find them in the graph
        # Pattern: {instruction}_enable or {instruction}_enable_and
        mux_inputs = []  # List of (enable_node_id, byte_enable_node_id)

        for instr_name, be_node_id in store_byte_enables.items():
            # Find the instruction enable signal
            enable_patterns = [
                f"{instr_name}_enable",
                f"{instr_name}_enable_and",
                f"{instr_name.replace('.', '_')}_enable",
            ]
            enable_node_id = None
            for pattern in enable_patterns:
                if pattern in graph.nodes:
                    enable_node_id = pattern
                    break

            if enable_node_id and be_node_id in graph.nodes:
                mux_inputs.append((enable_node_id, be_node_id))
                print(f"      {instr_name}: enable={enable_node_id}, byte_enable={be_node_id}")

        if not mux_inputs:
            continue

        # Create the combined byte enable mux node - use port name for uniqueness
        # Extract port identifier from write_port_node.id (e.g., "umem_shared_wr" -> "umem_shared")
        port_id = write_port_node.id
        if port_id.endswith('_wr'):
            port_id = port_id[:-3]
        combined_be_id = f"{port_id}_byte_enable"

        # Get byte enable width from first byte enable node
        first_be_node = graph.nodes.get(mux_inputs[0][1])
        be_width = first_be_node.data.get('bit_width', 4) if first_be_node else 4

        combined_be_node = Node(combined_be_id, {
            'type': 'byte_enable_mux',
            'name': combined_be_id,
            'bit_width': be_width,
            'mux_inputs': mux_inputs,  # Store for Verilog generator
            'default_value': (1 << be_width) - 1  # All ones for full word writes
        })
        graph.add_node(combined_be_node)

        # Add edges from enable and byte_enable nodes to the mux
        for enable_node_id, be_node_id in mux_inputs:
            enable_node = graph.nodes.get(enable_node_id)
            be_node = graph.nodes.get(be_node_id)
            if enable_node and be_node:
                graph.add_edge(Edge(enable_node, combined_be_node, data={'type': 'mux_select'}))
                graph.add_edge(Edge(be_node, combined_be_node, data={'type': 'mux_input'}))

        # Store the combined byte enable node ID on the write port
        write_port_node.data['combined_byte_enable'] = combined_be_id
        print(f"    Created combined byte enable: {combined_be_id}")
        last_combined_be_id = combined_be_id

    return last_combined_be_id


def get_externalized_memories(graph: ResourceGraph) -> List[str]:
    """Get list of memory names that have been marked for externalization."""
    externalized = []
    for node in graph.nodes.values():
        if node.data and node.data.get('is_memory') and node.data.get('externalized'):
            externalized.append(node.data.get('name', node.id))
    return externalized


def create_memory_stall_signals(graph: ResourceGraph, memory_name: str) -> Optional[Node]:
    """
    Create stall condition signals for an externalized memory.

    The stall condition is:
      stall = (read_req_valid && !read_resp_ready) || (write_req_valid && !write_resp_ready)

    This integrates with the pipeline stall controller to halt the processor
    while waiting for memory responses.

    Args:
        graph: Resource graph to modify
        memory_name: Name of the externalized memory

    Returns:
        The stall condition node, or None if memory is not externalized
    """
    # Find the memory node
    memory_node = None
    for node in graph.nodes.values():
        if node.data and node.data.get('name') == memory_name:
            if node.data.get('is_memory', False) and node.data.get('externalized'):
                memory_node = node
                break

    if not memory_node:
        print(f"Warning: Memory '{memory_name}' not found or not externalized")
        return None

    if not memory_node.data.get('use_valid_ready', False) and not memory_node.data.get('memory_variable_latency', False):
        print(f"  Memory '{memory_name}' not using variable latency, no stall signals needed")
        return None

    print(f"Creating stall signals for externalized memory '{memory_name}':")

    stall_conditions = []

    # Read stall: read_req_valid && !read_resp_ready
    if memory_node.data.get('externalize_read', True):
        # Create NOT(read_resp_ready)
        not_read_ready_id = f"{memory_name}_not_read_resp_ready"
        not_read_ready = Node(not_read_ready_id, {
            'type': 'operation',
            'operation': 'not',
            'bit_width': 1
        })
        graph.add_node(not_read_ready)

        # Create read stall condition: read_req_valid && !read_resp_ready
        read_stall_id = f"{memory_name}_read_stall"
        read_stall = Node(read_stall_id, {
            'type': 'operation',
            'operation': 'and',
            'bit_width': 1
        })
        graph.add_node(read_stall)

        stall_conditions.append(read_stall)
        print(f"  Created read stall: {read_stall_id}")

    # Write stall: write_req_valid && !write_resp_ready
    if memory_node.data.get('externalize_write', True):
        # Create NOT(write_resp_ready)
        not_write_ready_id = f"{memory_name}_not_write_resp_ready"
        not_write_ready = Node(not_write_ready_id, {
            'type': 'operation',
            'operation': 'not',
            'bit_width': 1
        })
        graph.add_node(not_write_ready)

        # Create write stall condition: write_req_valid && !write_resp_ready
        write_stall_id = f"{memory_name}_write_stall"
        write_stall = Node(write_stall_id, {
            'type': 'operation',
            'operation': 'and',
            'bit_width': 1
        })
        graph.add_node(write_stall)

        stall_conditions.append(write_stall)
        print(f"  Created write stall: {write_stall_id}")

    # Combine stall conditions with OR
    if len(stall_conditions) == 0:
        print(f"  No stall conditions created (no read/write ports enabled)")
        return None
    elif len(stall_conditions) == 1:
        stall_signal = stall_conditions[0]
    else:
        # Create OR of read and write stalls
        stall_or_id = f"{memory_name}_stall_condition"
        stall_or = Node(stall_or_id, {
            'type': 'operation',
            'operation': 'or',
            'bit_width': 1
        })
        graph.add_node(stall_or)

        # Connect stall conditions to OR
        for i, cond in enumerate(stall_conditions):
            edge = Edge(cond, stall_or, data={'type': 'operand', 'operand_index': i})
            graph.add_edge(edge)

        stall_signal = stall_or
        print(f"  Created combined stall: {stall_or_id}")

    # Store stall condition reference on memory node
    memory_node.data['stall_condition_node'] = stall_signal.id

    print(f"  Stall condition: {stall_signal.id}")
    return stall_signal


class MemoryPortInfo:
    """Information about an externalized memory port."""

    def __init__(self, memory_name: str, port_type: str, addr_width: int, data_width: int):
        self.memory_name = memory_name
        self.port_type = port_type  # 'read' or 'write'
        self.addr_width = addr_width
        self.data_width = data_width

    def get_port_signals(self, variable_latency: bool = False) -> Dict[str, dict]:
        """Get the signal definitions for this port.

        Returns:
            Dictionary mapping signal name to {'direction': 'input'|'output', 'width': int}
        """
        signals = {}
        prefix = f"{self.memory_name}_{self.port_type}_"

        if self.port_type == 'read':
            # Read request outputs (from processor)
            signals[f"{prefix}req_addr"] = {'direction': 'output', 'width': self.addr_width}
            signals[f"{prefix}req_valid"] = {'direction': 'output', 'width': 1}
            # Read response inputs (to processor)
            signals[f"{prefix}resp_data"] = {'direction': 'input', 'width': self.data_width}
            if variable_latency:
                signals[f"{prefix}resp_ready"] = {'direction': 'input', 'width': 1}
        else:  # write
            # Write request outputs (from processor)
            signals[f"{prefix}req_addr"] = {'direction': 'output', 'width': self.addr_width}
            signals[f"{prefix}req_data"] = {'direction': 'output', 'width': self.data_width}
            signals[f"{prefix}req_we"] = {'direction': 'output', 'width': self.data_width // 8}
            signals[f"{prefix}req_valid"] = {'direction': 'output', 'width': 1}
            # Write response inputs (to processor)
            if variable_latency:
                signals[f"{prefix}resp_ready"] = {'direction': 'input', 'width': 1}

        return signals
