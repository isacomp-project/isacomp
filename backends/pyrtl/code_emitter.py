"""
PyRTL Code Emitter

Serializes a PyRTL block to Python source code that recreates the design.
This allows PyRTL designs to be saved as .py files and loaded/simulated later.
"""

from typing import Dict, List, Set, Optional, TextIO
import pyrtl


def emit_pyrtl_code(block: pyrtl.Block, module_name: str = "design") -> str:
    """
    Convert a PyRTL block to Python source code that recreates it.

    Args:
        block: The PyRTL block to serialize
        module_name: Name for the generated module

    Returns:
        Python source code as a string
    """
    lines = []
    lines.append('"""')
    lines.append(f'PyRTL Design: {module_name}')
    lines.append('Generated by ISAComp PyRTL Backend')
    lines.append('"""')
    lines.append('')
    lines.append('import pyrtl')
    lines.append('')
    lines.append('')
    lines.append(f'def create_{module_name}():')
    lines.append('    """Create and return the PyRTL block for this design."""')
    lines.append('    pyrtl.reset_working_block()')
    lines.append('    ')

    # Track wire names we've declared
    declared_wires: Set[str] = set()
    wire_to_var: Dict[str, str] = {}  # Maps wire names to Python variable names

    # Helper to get valid Python variable name
    def var_name(wire_name: str) -> str:
        if wire_name in wire_to_var:
            return wire_to_var[wire_name]
        # Sanitize name for Python
        var = wire_name.replace('[', '_').replace(']', '_').replace('.', '_')
        var = var.replace("'", '_').replace('{', '_').replace('}', '_')
        var = var.replace(',', '_').replace(' ', '_').replace('-', '_')
        var = var.replace('+', '_plus_').replace('*', '_star_')
        var = var.replace('/', '_div_').replace('%', '_mod_')
        var = var.replace('<', '_lt_').replace('>', '_gt_')
        var = var.replace('=', '_eq_').replace('!', '_not_')
        var = var.replace('&', '_and_').replace('|', '_or_')
        var = var.replace('^', '_xor_').replace('~', '_inv_')
        var = var.replace('(', '_').replace(')', '_')
        var = var.replace('?', '_q_').replace(':', '_c_')
        if var and var[0].isdigit():
            var = '_' + var
        wire_to_var[wire_name] = var
        return var

    # First pass: declare all memories
    lines.append('    # Memories')
    for mem_name, mem in block.memblock_by_name.items():
        vn = var_name(mem_name)
        lines.append(f'    {vn} = pyrtl.MemBlock(bitwidth={mem.bitwidth}, addrwidth={mem.addrwidth}, name={repr(mem_name)}, max_read_ports={mem.max_read_ports}, max_write_ports={mem.max_write_ports}, asynchronous={mem.asynchronous})')
        declared_wires.add(mem_name)
    lines.append('    ')

    # Second pass: declare all inputs
    lines.append('    # Inputs')
    for wire in block.wirevector_set:
        if isinstance(wire, pyrtl.Input):
            vn = var_name(wire.name)
            lines.append(f'    {vn} = pyrtl.Input(bitwidth={len(wire)}, name={repr(wire.name)})')
            declared_wires.add(wire.name)
    lines.append('    ')

    # Third pass: declare all outputs (but don't assign yet)
    lines.append('    # Outputs')
    for wire in block.wirevector_set:
        if isinstance(wire, pyrtl.Output):
            vn = var_name(wire.name)
            lines.append(f'    {vn} = pyrtl.Output(bitwidth={len(wire)}, name={repr(wire.name)})')
            declared_wires.add(wire.name)
    lines.append('    ')

    # Fourth pass: declare all registers
    lines.append('    # Registers')
    for wire in block.wirevector_set:
        if isinstance(wire, pyrtl.Register):
            vn = var_name(wire.name)
            lines.append(f'    {vn} = pyrtl.Register(bitwidth={len(wire)}, name={repr(wire.name)})')
            declared_wires.add(wire.name)
    lines.append('    ')

    # Fifth pass: declare all constants
    lines.append('    # Constants')
    for wire in block.wirevector_set:
        if isinstance(wire, pyrtl.Const):
            vn = var_name(wire.name)
            lines.append(f'    {vn} = pyrtl.Const({wire.val}, bitwidth={len(wire)})')
            declared_wires.add(wire.name)
    lines.append('    ')

    # Build dependency graph to emit operations in correct order
    lines.append('    # Internal wires and logic')

    # Collect all wires that are destinations of operations
    dest_wires = set()
    for op in block.logic:
        for w in op.dests:
            dest_wires.add(w.name)

    # Declare internal wires that aren't destinations of operations
    # (these are wires that need to be pre-declared for <<= assignment)
    for wire in block.wirevector_set:
        if wire.name not in declared_wires and wire.name in dest_wires:
            # This wire is a destination - check if it's already handled by an op
            if not isinstance(wire, (pyrtl.Input, pyrtl.Output, pyrtl.Register, pyrtl.Const)):
                vn = var_name(wire.name)
                lines.append(f'    {vn} = pyrtl.WireVector(bitwidth={len(wire)}, name={repr(wire.name)})')
                declared_wires.add(wire.name)
    lines.append('    ')

    # Now emit all logic operations
    lines.append('    # Logic operations')
    for op in block.logic:
        dest_vars = [var_name(w.name) for w in op.dests]
        arg_vars = [var_name(w.name) for w in op.args]

        if op.op == 'w':  # Wire/assign
            if len(dest_vars) == 1 and len(arg_vars) == 1:
                lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]}')
        elif op.op == 'r':  # Register update (reg.next <<= value)
            # Check if dest is a Register
            if len(op.dests) > 0 and isinstance(op.dests[0], pyrtl.Register):
                lines.append(f'    {dest_vars[0]}.next <<= {arg_vars[0]}')
            else:
                lines.append(f'    # Unknown r op: {dest_vars[0]} <<= {arg_vars[0]}')
        elif op.op == '@':  # Write to memory
            if op.op_param is not None and len(op.op_param) > 0:
                mem_obj = None
                for item in op.op_param:
                    if hasattr(item, 'name') and hasattr(item, 'bitwidth'):
                        mem_obj = item
                        break
                if mem_obj is not None:
                    mem_var = var_name(mem_obj.name)
                    if len(arg_vars) >= 3:
                        lines.append(f'    {mem_var}[{arg_vars[0]}] <<= pyrtl.MemBlock.EnabledWrite({arg_vars[1]}, {arg_vars[2]})')
                    else:
                        lines.append(f'    {mem_var}[{arg_vars[0]}] <<= {arg_vars[1]}')
                else:
                    lines.append(f'    # Memory write: mem[{arg_vars[0]}] = {arg_vars[1] if len(arg_vars) > 1 else "?"} (MemBlock not found)')
            else:
                lines.append(f'    # Memory write: mem[{arg_vars[0]}] = {arg_vars[1] if len(arg_vars) > 1 else "?"} (op_param is None)')
        elif op.op == '+':
            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]} + {arg_vars[1]}')
        elif op.op == '-':
            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]} - {arg_vars[1]}')
        elif op.op == '*':
            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]} * {arg_vars[1]}')
        elif op.op == '&':
            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]} & {arg_vars[1]}')
        elif op.op == '|':
            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]} | {arg_vars[1]}')
        elif op.op == '^':
            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]} ^ {arg_vars[1]}')
        elif op.op == 'n':  # Negate
            lines.append(f'    {dest_vars[0]} <<= -{arg_vars[0]}')
        elif op.op == '~':  # Bitwise not
            lines.append(f'    {dest_vars[0]} <<= ~{arg_vars[0]}')
        elif op.op == '<':  # Less than (unsigned)
            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]} < {arg_vars[1]}')
        elif op.op == '>':  # Greater than (unsigned)
            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]} > {arg_vars[1]}')
        elif op.op == '=':  # Equal
            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]} == {arg_vars[1]}')
        elif op.op == 'x':  # Mux (select)
            # x: args = [sel, falsecase, truecase]
            lines.append(f'    {dest_vars[0]} <<= pyrtl.select({arg_vars[0]}, falsecase={arg_vars[1]}, truecase={arg_vars[2]})')
        elif op.op == 's':  # Select bits (slice)
            # s: op_param contains bit indices
            if op.op_param is not None:
                if isinstance(op.op_param, tuple):
                    if len(op.op_param) == 2:
                        low, high = op.op_param
                        lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]}[{low}:{high+1}]')
                    elif len(op.op_param) == 1:
                        bit = op.op_param[0]
                        lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]}[{bit}]')
                    else:
                        # Multiple bit indices - construct slice
                        indices = list(op.op_param)
                        if indices == list(range(min(indices), max(indices)+1)):
                            # Contiguous range
                            lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]}[{min(indices)}:{max(indices)+1}]')
                        else:
                            # Non-contiguous - need concat
                            bits = ', '.join(f'{arg_vars[0]}[{i}]' for i in indices)
                            lines.append(f'    {dest_vars[0]} <<= pyrtl.concat({bits})')
                else:
                    lines.append(f'    {dest_vars[0]} <<= {arg_vars[0]}[{op.op_param}]')
            else:
                lines.append(f'    # Slice with no op_param: {dest_vars[0]}')
        elif op.op == 'c':  # Concatenate
            args_str = ', '.join(arg_vars)
            lines.append(f'    {dest_vars[0]} <<= pyrtl.concat({args_str})')
        elif op.op == 'a':  # And reduce
            lines.append(f'    {dest_vars[0]} <<= pyrtl.and_all(*{arg_vars[0]})')
        elif op.op == 'o':  # Or reduce
            lines.append(f'    {dest_vars[0]} <<= pyrtl.or_all(*{arg_vars[0]})')
        elif op.op == 'm':  # Memory read OR Mux with multiple inputs
            # Check if it's a memory read (op_param contains MemBlock)
            mem_obj = None
            if op.op_param is not None:
                for item in op.op_param:
                    if hasattr(item, 'name') and hasattr(item, 'bitwidth') and hasattr(item, 'addrwidth'):
                        mem_obj = item
                        break

            if mem_obj is not None:
                # Memory read: dest = mem[addr]
                mem_var = var_name(mem_obj.name)
                lines.append(f'    {dest_vars[0]} <<= {mem_var}[{arg_vars[0]}]')
            else:
                # Multi-input mux
                sel_var = arg_vars[0]
                data_vars = arg_vars[1:]
                if len(data_vars) == 0:
                    lines.append(f'    # Empty mux: {dest_vars[0]} = mux({sel_var})')
                elif len(data_vars) == 1:
                    lines.append(f'    {dest_vars[0]} <<= {data_vars[0]}')
                elif len(data_vars) == 2:
                    lines.append(f'    {dest_vars[0]} <<= pyrtl.select({sel_var}, falsecase={data_vars[0]}, truecase={data_vars[1]})')
                else:
                    data_str = ', '.join(data_vars)
                    lines.append(f'    {dest_vars[0]} <<= pyrtl.select({sel_var}, *[{data_str}])')
        else:
            lines.append(f'    # Unknown op: {op.op} dests={dest_vars} args={arg_vars}')

    lines.append('    ')
    lines.append('    return pyrtl.working_block()')
    lines.append('')
    lines.append('')

    # Add module-level block creation
    lines.append('# Create the design when this module is imported')
    lines.append(f'block = create_{module_name}()')
    lines.append('')

    return '\n'.join(lines)


def write_pyrtl_design(block: pyrtl.Block, filepath: str, module_name: str = "design"):
    """Write a PyRTL block to a Python file."""
    code = emit_pyrtl_code(block, module_name)
    with open(filepath, 'w') as f:
        f.write(code)
