#!/usr/bin/env python3
"""
Run riscv-tests on VHDL processor generated by ISAComp.

This script:
1. Builds riscv-tests for the ISAComp environment
2. Generates VHDL testbenches for each test
3. Runs simulations with GHDL
4. Reports pass/fail results
"""

import subprocess
import sys
from pathlib import Path
from typing import Optional, Tuple, List
import tempfile
import shutil

# Import ISAComp modules
from core.isa_parser import parse_isa_file
from core.graph_merger import merge_instructions
from backends.vhdl import generate_vhdl_with_testbench, VHDLTestbenchConfig, load_elf_for_testbench
from backends.vhdl.testbench_generator import generate_vhdl_testbench_files


def compile_riscv_test(test_name: str, test_src: Path, output_path: Path) -> Tuple[bool, Optional[int], Optional[int]]:
    """
    Compile a riscv-test and extract pass/fail addresses.

    Returns: (success, pass_addr, fail_addr)
    """
    print(f"  Compiling {test_name}...", end=" ", flush=True)

    # Compile test
    cmd = [
        "riscv64-unknown-elf-gcc",
        "-march=rv32i", "-mabi=ilp32",
        "-static", "-mcmodel=medany",
        "-fvisibility=hidden",
        "-nostdlib", "-nostartfiles",
        "-I", "riscv-tests/env/isacomp",
        "-I", "riscv-tests/isa/macros/scalar",
        "-T", "riscv-tests/env/isacomp/link.ld",
        str(test_src),
        "-o", str(output_path)
    ]

    result = subprocess.run(cmd, capture_output=True, text=True)

    if result.returncode != 0:
        print(f"FAILED (compilation error)")
        print(f"    {result.stderr}")
        return False, None, None

    # Extract pass/fail addresses
    nm_result = subprocess.run(
        ["riscv64-unknown-elf-nm", str(output_path)],
        capture_output=True,
        text=True
    )

    pass_addr = None
    fail_addr = None

    for line in nm_result.stdout.split('\n'):
        if 'pass' in line and not 'PASS' in line:
            pass_addr = int(line.split()[0], 16)
        if 'fail' in line and not 'FAIL' in line:
            fail_addr = int(line.split()[0], 16)

    if pass_addr is None or fail_addr is None:
        print(f"FAILED (no pass/fail symbols)")
        return False, None, None

    print(f"OK (pass=0x{pass_addr:x}, fail=0x{fail_addr:x})")
    return True, pass_addr, fail_addr


def run_vhdl_test(test_name: str, test_elf: Path, processor_vhdl: Path,
                  pass_addr: int, fail_addr: int, work_dir: Path) -> Optional[bool]:
    """
    Run a single test on the VHDL processor.

    Returns: True if passed, False if failed, None if error
    """
    print(f"  Running VHDL simulation for {test_name}...", end=" ", flush=True)

    try:
        # Load ELF and get program data (split into imem and dmem)
        imem_data, dmem_data, elf_pass, elf_fail = load_elf_for_testbench(
            test_elf,
            imem_size=16384,  # 16K words
            dmem_size=16384   # 16K words
        )

        # Use extracted addresses if ELF loader didn't find them
        if elf_pass is None:
            elf_pass = pass_addr
        if elf_fail is None:
            elf_fail = fail_addr

        # Generate testbench
        config = VHDLTestbenchConfig(
            entity_name="riscv32i_complete",
            timeout_cycles=10000,  # 10k cycles timeout
            debug_outputs=['pc_rd']  # Expose PC for pass/fail detection
        )

        files = generate_vhdl_testbench_files(
            entity_name="riscv32i_complete",
            rtl_file=processor_vhdl,
            output_dir=work_dir,
            config=config,
            program_data=imem_data,
            dmem_data=dmem_data,
            pass_addr=elf_pass,
            fail_addr=elf_fail
        )

        # Compile processor (always reanalyze to avoid stale file errors)
        result = subprocess.run(
            ["ghdl", "-a", "--std=08", processor_vhdl.name],
            cwd=work_dir,
            capture_output=True,
            text=True
        )
        if result.returncode != 0:
            print(f"ERROR (processor compilation failed)")
            print(f"    {result.stderr}")
            return None

        # Compile testbench
        result = subprocess.run(
            ["ghdl", "-a", "--std=08", files['testbench'].name],
            cwd=work_dir,
            capture_output=True,
            text=True
        )
        if result.returncode != 0:
            print(f"ERROR (testbench compilation failed)")
            print(f"    {result.stderr}")
            return None

        # Elaborate
        result = subprocess.run(
            ["ghdl", "-e", "--std=08", "riscv32i_complete_tb"],
            cwd=work_dir,
            capture_output=True,
            text=True
        )
        if result.returncode != 0:
            print(f"ERROR (elaboration failed)")
            print(f"    {result.stderr}")
            return None

        # Run simulation
        result = subprocess.run(
            ["ghdl", "-r", "--std=08", "riscv32i_complete_tb", "--stop-time=100us"],
            cwd=work_dir,
            capture_output=True,
            text=True,
            timeout=30
        )

        # Check results
        output = result.stdout + result.stderr

        if "TEST PASSED" in output:
            print("PASSED ✓")
            return True
        elif "TEST FAILED" in output:
            print("FAILED ✗")
            return False
        elif "TIMEOUT" in output or "timeout" in output.lower():
            print("TIMEOUT ⏱")
            return False
        else:
            print(f"UNKNOWN (no clear result)")
            if result.returncode != 0:
                print(f"    Exit code: {result.returncode}")
            return None

    except subprocess.TimeoutExpired:
        print("TIMEOUT ⏱")
        return False
    except Exception as e:
        print(f"ERROR ({str(e)})")
        return None


def main():
    """Main test runner."""
    print("=" * 70)
    print("ISAComp VHDL RISC-V Test Runner")
    print("=" * 70)
    print()

    # Check that processor VHDL exists
    processor_vhdl = Path("vhdl/riscv32i_complete/riscv32i_complete.vhd")
    if not processor_vhdl.exists():
        print(f"ERROR: Processor VHDL not found at {processor_vhdl}")
        print("Please run generate_riscv32i_complete_vhdl.py first")
        sys.exit(1)

    # List of tests to run (matching our implemented instructions)
    # Get test list from command line or use default subset
    if len(sys.argv) > 1:
        tests = sys.argv[1:]
    else:
        # Default: run all supported tests
        tests = [
            "add", "addi", "sub", "lui", "auipc",
            "and", "andi", "or", "ori", "xor", "xori",
            "sll", "slli", "srl", "srli", "srai",
            "slt", "slti", "sltu", "sltiu",
            "beq", "bne", "blt", "bltu", "bge", "bgeu",
            "jal", "jalr",
            "lw", "lh", "lhu", "lb", "lbu",
            "sw", "sh", "sb"
        ]

    # Create temp working directory for tests
    work_dir = Path("vhdl_test_work")
    work_dir.mkdir(exist_ok=True)

    # Copy processor VHDL to work directory
    processor_vhdl_abs = processor_vhdl.resolve()
    work_processor = work_dir / processor_vhdl.name
    shutil.copy(processor_vhdl_abs, work_processor)
    processor_vhdl = work_processor  # Use the copied file

    # Results tracking
    compiled = 0
    passed = 0
    failed = 0
    errors = 0

    print(f"Running {len(tests)} tests")
    print()

    for test_name in tests:
        print(f"{test_name}:")

        # Check if test source exists
        test_src = Path(f"riscv-tests/isa/rv32ui/{test_name}.S")
        if not test_src.exists():
            print(f"  SKIP (no test source)")
            errors += 1
            continue

        # Compile test
        test_elf = work_dir / f"rv32ui-isacomp-{test_name}"
        success, pass_addr, fail_addr = compile_riscv_test(test_name, test_src, test_elf)

        if not success:
            errors += 1
            continue

        compiled += 1

        # Run test
        result = run_vhdl_test(
            test_name, test_elf, processor_vhdl,
            pass_addr, fail_addr, work_dir
        )

        if result is True:
            passed += 1
        elif result is False:
            failed += 1
        else:
            errors += 1

        print()

    # Summary
    print("=" * 70)
    print("Test Results Summary")
    print("=" * 70)
    print(f"Compiled: {compiled}/{len(tests)}")
    print(f"Passed:   {passed}")
    print(f"Failed:   {failed}")
    print(f"Errors:   {errors}")
    print()

    if passed == len(tests):
        print("🎉 All tests PASSED!")
        sys.exit(0)
    elif failed > 0:
        print(f"❌ {failed} tests FAILED")
        sys.exit(1)
    else:
        print(f"⚠️  {errors} tests had errors")
        sys.exit(2)


if __name__ == "__main__":
    main()
