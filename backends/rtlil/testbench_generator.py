"""
CXXRTL testbench generator for ISAComp.

Generates a generic C++ testbench driver that works with any CXXRTL-compiled
design. Discovers ports from the ResourceGraph (not ISA-specific).
"""

from typing import Dict, List, Optional
from pathlib import Path
from core.resource_graph import ResourceGraph


class CXXRTLTestbenchConfig:
    """Configuration for CXXRTL testbench generation."""

    def __init__(self, module_name: str = "processor",
                 timeout_cycles: int = 10000,
                 namespace: str = "cxxrtl_design",
                 vcd_trace: bool = True,
                 pc_signal: Optional[str] = None,
                 pass_addr: Optional[int] = None,
                 fail_addr: Optional[int] = None):
        self.module_name = module_name
        self.timeout_cycles = timeout_cycles
        self.namespace = namespace
        self.vcd_trace = vcd_trace
        self.pc_signal = pc_signal    # e.g., "pc_rd" for RISC-V
        self.pass_addr = pass_addr
        self.fail_addr = fail_addr


def _cxxrtl_mangle(name: str) -> str:
    """Convert an RTLIL-style name to CXXRTL C++ member name.

    CXXRTL replaces each ``_`` in the original identifier with ``__``.
    E.g. ``pc_rd`` -> ``pc__rd``, ``reset_pc_rd`` -> ``reset__pc__rd``.
    """
    return name.replace('_', '__')


def generate_cxxrtl_testbench(graph: ResourceGraph,
                              config: CXXRTLTestbenchConfig,
                              output_dir: str) -> Dict[str, Path]:
    """Generate C++ testbench driver for CXXRTL simulation.

    Discovers memory names and register ports generically from the graph.

    Args:
        graph: The ResourceGraph used for code generation.
        config: Testbench configuration.
        output_dir: Directory to write output files.

    Returns:
        Dictionary mapping file type names to Paths.
    """
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    # Discover memories from graph
    memories = []
    for node in sorted(graph.nodes.values(), key=lambda n: n.id):
        if node.data.get('is_memory', False) and node.data.get('type') in ('isa_state', 'isa_state mem'):
            name = node.data.get('name', node.id)
            width = node.data.get('port_width') or node.data.get('bit_width', 32)
            raw_depth = node.data.get('array_depth', 5)
            if node.data.get('is_cam', False):
                depth = raw_depth
            else:
                depth = min(2 ** raw_depth, 67108864)
            memories.append({
                'name': name,
                'width': width,
                'depth': depth,
            })

    # Discover scalar ISA state for reset inputs
    reset_inputs = []
    for node in sorted(graph.nodes.values(), key=lambda n: n.id):
        if (node.id.endswith('_rd') and node.is_arch_state and
                not node.data.get('is_memory', False) and
                node.data.get('type') == 'isa_state'):
            name = node.id
            width = node.data.get('bit_width', 32)
            reset_inputs.append({'name': name, 'width': width})

    # Detect PC signal for pass/fail checking
    pc_signal = config.pc_signal
    if not pc_signal:
        for ri in reset_inputs:
            if 'pc' in ri['name'].lower():
                pc_signal = ri['name']
                break

    # CXXRTL module class name: p_{mangled_module_name}
    mod_cxx = f"p_{_cxxrtl_mangle(config.module_name)}"

    # --- Generate driver C++ ---
    driver = []
    driver.append(f"// Auto-generated CXXRTL testbench for {config.module_name}")
    driver.append(f"// Generated by ISAComp RTLIL backend")
    driver.append(f"#include <iostream>")
    driver.append(f"#include <fstream>")
    driver.append(f"#include <sstream>")
    driver.append(f"#include <string>")
    driver.append(f"#include <cstdint>")
    driver.append(f"#include <cstdlib>")
    if config.vcd_trace:
        driver.append(f"#include <backends/cxxrtl/cxxrtl_vcd.h>")
    driver.append(f"")
    driver.append(f"using namespace {config.namespace};")
    driver.append(f"")

    # Memory hex loader - loads word-addressed hex (one 32-bit word per line)
    driver.append(f"// Load word-addressed hex file into CXXRTL memory")
    driver.append(f"template<typename M>")
    driver.append(f"bool load_hex(M &mem, size_t depth, const std::string &path) {{")
    driver.append(f"    std::ifstream f(path);")
    driver.append(f"    if (!f.is_open()) return false;")
    driver.append(f"    std::string line;")
    driver.append(f"    size_t addr = 0;")
    driver.append(f"    while (std::getline(f, line) && addr < depth) {{")
    driver.append(f"        if (line.empty() || line[0] == '/' || line[0] == '#') continue;")
    driver.append(f"        if (line[0] == '@') {{")
    driver.append(f"            addr = std::stoul(line.substr(1), nullptr, 16);")
    driver.append(f"            continue;")
    driver.append(f"        }}")
    driver.append(f"        uint32_t val = std::stoul(line, nullptr, 16);")
    driver.append(f"        mem[addr].template set<uint32_t>(val);")
    driver.append(f"        addr++;")
    driver.append(f"    }}")
    driver.append(f"    return true;")
    driver.append(f"}}")
    driver.append(f"")

    driver.append(f"int main(int argc, char **argv) {{")
    driver.append(f"    {mod_cxx} top;")
    driver.append(f"")

    # Parse command line args for pass/fail addresses and hex files
    driver.append(f"    uint32_t pass_addr = 0xFFFFFFFF;")
    driver.append(f"    uint32_t fail_addr = 0xFFFFFFFE;")
    driver.append(f"    std::string vcd_file;")
    driver.append(f"    std::string hex_file;")
    driver.append(f"    int timeout = {config.timeout_cycles};")
    driver.append(f"")
    driver.append(f"    for (int i = 1; i < argc; i++) {{")
    driver.append(f"        std::string arg = argv[i];")
    driver.append(f'        if (arg.substr(0, 11) == "+pass_addr=") pass_addr = std::stoul(arg.substr(11), nullptr, 16);')
    driver.append(f'        else if (arg.substr(0, 11) == "+fail_addr=") fail_addr = std::stoul(arg.substr(11), nullptr, 16);')
    driver.append(f'        else if (arg.substr(0, 5) == "+vcd=") vcd_file = arg.substr(5);')
    driver.append(f'        else if (arg.substr(0, 5) == "+hex=") hex_file = arg.substr(5);')
    driver.append(f'        else if (arg.substr(0, 9) == "+timeout=") timeout = std::stoi(arg.substr(9));')
    driver.append(f"    }}")
    driver.append(f"")

    # Load memory hex files
    # Only load +hex= into the largest memory (program/unified memory).
    # Register files and small memories get their own default hex files.
    largest_mem = max(memories, key=lambda m: m['depth']) if memories else None
    for mem in memories:
        mn = _cxxrtl_mangle(mem['name'])
        driver.append(f"    // Load {mem['name']} memory ({mem['depth']} x {mem['width']}-bit)")
        if mem is largest_mem:
            driver.append(f'    if (!hex_file.empty()) {{')
            driver.append(f'        if (!load_hex(top.memory_p_{mn}, {mem["depth"]}, hex_file))')
            driver.append(f'            std::cerr << "Warning: could not load " << hex_file << std::endl;')
            driver.append(f'    }} else {{')
            driver.append(f'        load_hex(top.memory_p_{mn}, {mem["depth"]}, "{mem["name"]}.hex");')
            driver.append(f'    }}')
        else:
            # Small memories (register files etc.) load from their own hex file
            driver.append(f'    load_hex(top.memory_p_{mn}, {mem["depth"]}, "{mem["name"]}.hex");')
    driver.append(f"")

    # VCD setup
    if config.vcd_trace:
        driver.append(f"    cxxrtl::vcd_writer vcd;")
        driver.append(f"    if (!vcd_file.empty()) {{")
        driver.append(f"        cxxrtl::debug_items di;")
        driver.append(f'        top.debug_info(di, "");')
        driver.append(f'        vcd.timescale(1, "ns");')
        driver.append(f"        vcd.add(di);")
        driver.append(f"    }}")
        driver.append(f"")

    # Reset sequence
    driver.append(f"    // Reset")
    driver.append(f"    top.p_reset.set<bool>(true);")
    for ri in reset_inputs:
        rn = _cxxrtl_mangle(ri['name'])
        driver.append(f"    top.p_reset__{rn}.set<uint32_t>(0);")
    driver.append(f"    for (int i = 0; i < 3; i++) {{")
    driver.append(f"        top.p_clk.set<bool>(false);")
    driver.append(f"        top.step();")
    if config.vcd_trace:
        driver.append(f"        if (!vcd_file.empty()) vcd.sample(i*2);")
    driver.append(f"        top.p_clk.set<bool>(true);")
    driver.append(f"        top.step();")
    if config.vcd_trace:
        driver.append(f"        if (!vcd_file.empty()) vcd.sample(i*2+1);")
    driver.append(f"    }}")
    driver.append(f"    top.p_reset.set<bool>(false);")
    driver.append(f"")

    # Detect pipelined design: look for Execute-stage PC and validity signals.
    # The execution stage may be named differently depending on pipeline depth:
    #   5-stage: Execute, 4-stage: Execute, 3-stage: ExecuteMemoryWriteback, 2-stage: ExecuteMemoryWriteback
    exec_pc_signal = None
    exec_valid_signal = None
    rf_mem = None
    for node in graph.nodes.values():
        nid = node.id
        # Find validity signal: PIPE_{stage}_valid_PIPE where stage contains "Execute"
        if ('Execute' in nid and nid.endswith('_valid_PIPE') and nid.startswith('PIPE_')
                and node.data.get('type') in ('pipeline_register', 'validity_bit')):
            exec_valid_signal = nid
        # Find PC pipeline register: contains both 'Execute' and pc_signal name
        if ('PIPE' in nid and 'Execute' in nid and pc_signal and pc_signal in nid
                and nid.endswith('_PIPE') and node.data.get('type') == 'pipeline_register'):
            exec_pc_signal = nid
        if (node.data.get('is_memory', False) and node.data.get('type') in ('isa_state', 'isa_state mem')
                and node.data.get('name') == 'rf'):
            rf_mem = node

    # Main simulation loop
    driver.append(f"    // Run simulation")
    if exec_pc_signal and exec_valid_signal:
        driver.append(f"    // Check Execute-stage PC with validity (not fetch PC) to avoid")
        driver.append(f"    // false pass/fail from speculative fetches in the pipeline.")
    driver.append(f"    for (int cycle = 0; cycle < timeout; cycle++) {{")
    driver.append(f"        top.p_clk.set<bool>(false);")
    driver.append(f"        top.step();")
    if config.vcd_trace:
        driver.append(f"        if (!vcd_file.empty()) vcd.sample(6 + cycle*2);")
    driver.append(f"        top.p_clk.set<bool>(true);")
    driver.append(f"        top.step();")
    if config.vcd_trace:
        driver.append(f"        if (!vcd_file.empty()) vcd.sample(6 + cycle*2+1);")
    driver.append(f"")

    # Check pass/fail - use Execute-stage PC with validity for pipelined designs
    if exec_pc_signal and exec_valid_signal and pc_signal:
        epc_cxx = _cxxrtl_mangle(exec_pc_signal)
        eval_cxx = _cxxrtl_mangle(exec_valid_signal)
        driver.append(f"        uint32_t exec_pc = top.p_{epc_cxx}.get<uint32_t>();")
        driver.append(f"        bool exec_valid = top.p_{eval_cxx}.get<bool>();")
        driver.append(f"        if (exec_valid && exec_pc == pass_addr) {{")
        driver.append(f'            std::cout << "TEST PASSED" << std::endl;')
        driver.append(f"            goto done;")
        driver.append(f"        }}")
        driver.append(f"        if (exec_valid && exec_pc == fail_addr) {{")
        if rf_mem:
            rf_cxx = _cxxrtl_mangle(rf_mem.data.get('name', 'rf'))
            driver.append(f'            std::cout << "TEST FAILED at pc=0x" << std::hex << exec_pc')
            driver.append(f'                      << " test=" << std::dec << top.memory_p_{rf_cxx}[3].get<uint32_t>() << std::endl;')
        else:
            driver.append(f'            std::cout << "TEST FAILED at pc=0x" << std::hex << exec_pc << std::endl;')
        driver.append(f"            goto done;")
        driver.append(f"        }}")
    elif pc_signal:
        pc_cxx = _cxxrtl_mangle(pc_signal)
        driver.append(f"        uint32_t pc = top.p_{pc_cxx}.get<uint32_t>();")
        driver.append(f"        if (pc == pass_addr) {{")
        driver.append(f'            std::cout << "TEST PASSED" << std::endl;')
        driver.append(f"            goto done;")
        driver.append(f"        }}")
        driver.append(f"        if (pc == fail_addr) {{")
        driver.append(f'            std::cout << "TEST FAILED at pc=0x" << std::hex << pc << std::endl;')
        driver.append(f"            goto done;")
        driver.append(f"        }}")

    driver.append(f"    }}")
    driver.append(f'    std::cout << "TIMEOUT" << std::endl;')
    driver.append(f"")
    driver.append(f"done:")
    if config.vcd_trace:
        driver.append(f"    if (!vcd_file.empty()) {{")
        driver.append(f"        std::ofstream vf(vcd_file);")
        driver.append(f"        vf << vcd.buffer;")
        driver.append(f"    }}")
    driver.append(f"    return 0;")
    driver.append(f"}}")

    driver_path = out / f"{config.module_name}_tb.cpp"
    driver_path.write_text("\n".join(driver) + "\n")

    files = {'testbench': driver_path}

    return files


def copy_test_scripts(template_dir: str, output_dir: str,
                      module_name: str,
                      template_name: str = "riscv32i_pipelined") -> Dict[str, Path]:
    """Copy test scripts from canonical template directory with module-name substitution.

    Mirrors the HardCaml backend pattern: a single canonical copy of
    run_all_tests.sh and compile.sh lives in the template directory, and
    each per-configuration output directory gets a copy with the module name
    substituted.

    Args:
        template_dir: Path to canonical template directory
                      (e.g. ``examples/rtlil/riscv32i_pipelined``).
        output_dir: Per-configuration output directory.
        module_name: Target module name (e.g. ``riscv32i_pipelined_5stage``).
        template_name: Default module name used in the template scripts.

    Returns:
        Dictionary mapping script names to output Paths.
    """
    import os
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)

    files = {}
    for script_name in ['run_all_tests.sh', 'compile.sh']:
        src = os.path.join(template_dir, script_name)
        if os.path.exists(src):
            with open(src, 'r') as f:
                content = f.read()
            content = content.replace(template_name, module_name)
            dst = out / script_name
            dst.write_text(content)
            dst.chmod(0o755)
            files[script_name] = dst

    return files
