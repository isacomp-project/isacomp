class SMTContext:
    """Manages SMT variables, constraints, and formula generation."""

    def __init__(self):
        self.declarations: List[str] = []
        self.constraints: List[str] = []
        self.variable_names: Set[str] = set()
        self.node_to_var: Dict[str, str] = {}
        self.fresh_counter = 0
        self.bool_variables: Set[str] = set()  # Track which variables are Bool type

    @staticmethod
    def _sorted_edges(edges):
        """Sort edges deterministically by ID to ensure consistent SMT generation.

        ResourceGraph stores edges in Sets which have non-deterministic iteration order.
        This causes the SMT converter to generate different formulas on different runs,
        leading to non-deterministic verification results.

        Args:
            edges: Set or iterable of Edge objects

        Returns:
            List of edges sorted by edge ID
        """
        return sorted(edges, key=lambda e: e.id)

    def fresh_var(self, prefix: str = "tmp") -> str:
        """Generate a fresh variable name."""
        name = f"{prefix}_{self.fresh_counter}"
        self.fresh_counter += 1
        return name

    def declare_bv(self, name: str, width: int) -> str:
        """Declare a bitvector variable."""
        if name not in self.variable_names:
            self.declarations.append(f"(declare-const {name} (_ BitVec {width}))")
            self.variable_names.add(name)
        return name

    def declare_bool(self, name: str) -> str:
        """Declare a boolean variable."""
        if name not in self.variable_names:
            self.declarations.append(f"(declare-const {name} Bool)")
            self.variable_names.add(name)
            self.bool_variables.add(name)  # Track as Bool type
        return name

    def is_bool_var(self, var_name: str) -> bool:
        """Check if a variable is Bool type."""
        return var_name in self.bool_variables

    def declare_array(self, name: str, index_width: int, value_width: int) -> str:
        """Declare an array variable (for register files, memory)."""
        if name not in self.variable_names:
            self.declarations.append(
                f"(declare-const {name} (Array (_ BitVec {index_width}) (_ BitVec {value_width})))"
            )
            self.variable_names.add(name)
        return name

    def add_constraint(self, constraint: str):
        """Add an SMT constraint (assertion)."""
        self.constraints.append(f"(assert {constraint})")

    def to_smt_lib2(self) -> str:
        """Generate complete SMT-LIB2 formula."""
        lines = [
            "; SMT-LIB2 formula generated by isacomp verification",
            "(set-logic ABV)  ; Arrays + Bitvectors with quantifiers",
            ""
        ]

        # Add declarations
        if self.declarations:
            lines.append("; Variable declarations")
            lines.extend(self.declarations)
            lines.append("")

        # Add constraints
        if self.constraints:
            lines.append("; Constraints")
            lines.extend(self.constraints)
            lines.append("")

        return "\n".join(lines)


class ResourceGraphToSMT:
    """Converts resource graphs to SMT formulas."""

    def __init__(self, graph: ResourceGraph, name_prefix: str = "", target_mem_addr_widths: dict = None):
        self.graph = graph
        self.name_prefix = name_prefix
        self.ctx = SMTContext()
        # ILA graphs have swapped right shift operators (bug in ILA encoding)
        # >> in ILA = arithmetic shift (should be logical)
        # >>> in ILA = logical shift (should be arithmetic)
        self.is_ila_graph = (name_prefix == "ila_")
        # Target memory address widths from ISA graph (for ILA to match)
        self.target_mem_addr_widths = target_mem_addr_widths or {}

    @staticmethod
    def _sorted_edges(edges):
        """Sort edges deterministically by ID to ensure consistent SMT generation.

        ResourceGraph stores edges in Sets which have non-deterministic iteration order.
        This causes the SMT converter to generate different formulas on different runs,
        leading to non-deterministic verification results.

        Args:
            edges: Set or iterable of Edge objects

        Returns:
            List of edges sorted by edge ID
        """
        return sorted(edges, key=lambda e: e.id)

    def get_node_var(self, node: Node, suffix: str = "") -> str:
        """Get or create SMT variable name for a node."""
        # Redirect split base nodes to their _rd version for reads
        # (e.g., if asking for 'rf_in', redirect to 'rf_rd_in')
        node_id = node.id
        if suffix == "_in":
            # Check if this is a split base node
            if f'{node_id}_rd' in self.graph.nodes and f'{node_id}_wr' in self.graph.nodes:
                # Redirect to _rd node for input reads
                node = self.graph.nodes[f'{node_id}_rd']

        key = f"{node.id}{suffix}"
        if key not in self.ctx.node_to_var:
            # Create a sanitized variable name using node ID
            # Map operators to readable names to avoid collisions
            base_name = node.id
            base_name = base_name.replace('+', '_plus_')
            base_name = base_name.replace('-', '_minus_')
            base_name = base_name.replace('*', '_mult_')
            base_name = base_name.replace('/', '_div_')
            base_name = base_name.replace('%', '_mod_')
            base_name = base_name.replace('&', '_and_')
            base_name = base_name.replace('|', '_or_')
            base_name = base_name.replace('^', '_xor_')
            base_name = base_name.replace('~', '_not_')
            base_name = base_name.replace('<', '_lt_')
            base_name = base_name.replace('>', '_gt_')
            base_name = base_name.replace('=', '_eq_')
            base_name = base_name.replace('!', '_bang_')
            base_name = base_name.replace('<<', '_shl_')
            base_name = base_name.replace('>>', '_shr_')
            # Replace remaining non-alphanumeric characters
            base_name = re.sub(r'[^a-zA-Z0-9_]', '_', base_name)
            var_name = f"{self.name_prefix}{base_name}{suffix}"
            self.ctx.node_to_var[key] = var_name
        return self.ctx.node_to_var[key]

    def get_value_var(self, node: Node) -> str:
        """
        Get the SMT variable representing the value of a node.

        For state nodes (isa_state, var, uarch_state), this returns the _in version
        since we're reading the input value. For array_access reads, this returns
        a select operation. For literals, this returns the inline literal value.
        For other nodes (operations, etc.), this returns the base variable name.
        """
        node_type = node.data.get('type')
        if node_type in ['isa_state', 'architectural_state', 'var', 'uarch_state']:
            # Check if this is a SAIL constant var (log2_xlen, xlen)
            if node_type == 'var' and len(node.incoming_edges) == 0:
                display_name = node.data.get('display_name', '')
                if display_name == 'log2_xlen':
                    # For RV32: log2(32) = 5
                    return "(_ bv5 32)"
                elif display_name == 'xlen':
                    # For RV32: xlen = 32
                    return "(_ bv32 32)"
            return self.get_node_var(node, "_in")
        elif node_type == 'array_access':
            # ISA array access: generate (select array index) - inlined
            return self.convert_array_read(node)
        elif node_type == 'memory_read':
            # ILA memory read: use variable (not inlined, has constraint)
            return self.get_node_var(node)
        elif node_type == 'memory_write':
            # ILA memory_write: generate (store array index value)
            return self.convert_memory_write(node)
        elif node_type == 'conditional':
            # Check if this conditional produces an array (selects between arrays)
            # If so, inline the ITE expression
            for edge in self._sorted_edges(node.incoming_edges):
                if edge.data.get('type') == 'ternary_true':
                    source = edge.source
                    source_type = source.data.get('type')
                    if source_type in ['isa_state', 'architectural_state'] and (
                        len(source.data.get('dimensions') or []) > 1 or source.data.get('is_memory', False)
                    ):
                        # This conditional produces an array - inline it
                        return self.convert_ternary_op(node)
                    if source_type in ['memory_write', 'memory_read']:
                        # This conditional selects between memory operations - inline it
                        return self.convert_ternary_op(node)
                    break
            # Otherwise use the node variable
            return self.get_node_var(node)
        elif node_type == 'literal':
            # Inline literal values instead of using variables
            return self.convert_literal(node)
        elif node_type == 'sign_extend':
            # Inline sign_extend expression to avoid width mismatch errors
            return self.convert_sign_extend(node)
        elif node_type == 'zero_extend':
            # Inline zero_extend expression to avoid width mismatch errors
            return self.convert_zero_extend(node)
        else:
            return self.get_node_var(node)

    def convert_array_read(self, node: Node) -> str:
        """Convert an array_access or memory_read to SMT select operation."""
        # Find the array and index from incoming edges
        array_node = None
        index_node = None

        # First, try ISA-style array_index/array_base edges
        for edge in self._sorted_edges(node.incoming_edges):
            edge_type = edge.data.get('type')
            if edge_type in ('array_index', 'array_base'):
                source = edge.source
                source_type = source.data.get('type')
                # Array is isa_state or architectural_state with multiple dimensions OR is_memory flag
                if (source_type.startswith('isa_state') or source_type == 'architectural_state') and (
                    len(source.data.get('dimensions') or []) > 1 or source.data.get('is_memory', False)
                ):
                    array_node = source
                elif edge_type == 'array_index':
                    # This is the index (only for old-style array_index edges)
                    index_node = source

        # If not found, try ILA-style operand edges with position
        if not array_node or not index_node:
            operands = [(edge.data.get('position', -1), edge.source) for edge in node.incoming_edges
                       if edge.data.get('type') == 'operand']
            operands.sort(key=lambda x: x[0])  # Sort by position

            if len(operands) >= 2:
                # For memory_read: operand[0] = array, operand[1] = index
                array_node = operands[0][1]
                index_node = operands[1][1]

        if not array_node or not index_node:
            raise ValueError(f"Array access {node.id} missing array or index")

        # Check if this memory uses byte-wise representation
        is_bytewise = array_node.id in getattr(self, 'bytewise_memories', set())

        if is_bytewise:
            # Byte-wise memory - determine access width from the target variable
            # Find what variable this read assigns to
            read_width = None
            for edge in self._sorted_edges(node.outgoing_edges):
                if edge.data.get('type') == 'assignment':
                    target_node = edge.target
                    read_width = self.get_node_width(target_node)
                    break

            # If no assignment found, use the read node's own width
            if read_width is None:
                read_width = self.get_node_width(node)

            if read_width and read_width > 8:
                # Multi-byte access - decompose into byte reads and concatenate
                array_var = self.get_node_var(array_node, "_in")
                index_var = self.get_value_var(index_node)

                # Get the expected byte address width
                # For word-addressed memories (data_width > 8), this includes the byte offset bits
                data_width = array_node.data.get('data_width') or array_node.data.get('bit_width', 8)
                # Use original_data_width if available (for byte-wise converted memories)
                original_data_width = array_node.data.get('original_data_width', data_width)
                addr_bits = array_node.data.get('addr_bits') or array_node.data.get('addr_width', 10)
                actual_index_width = self.get_node_width(index_node)

                # Convert word address to byte address if needed
                # Use original_data_width to check if scaling is needed
                if original_data_width > 8:
                    import math
                    byte_offset_bits = int(math.log2(original_data_width // 8))

                    # Determine if index is a byte address or word address
                    # ISA uses full 32-bit byte addresses (PC) even when indexing word-addressed memory
                    # ILA uses word addresses (e.g., 30-bit from PC[31:2])
                    target_word_addr_width = addr_bits - byte_offset_bits

                    if actual_index_width == 32:
                        # Index is exactly 32 bits - this is a byte address (e.g., ISA's PC)
                        # Extract word address first: index[31:2], then truncate to target width
                        index_var = f"((_ extract 31 2) {index_var})"
                        word_addr_width = 30  # 32-bit byte addr -> 30-bit word addr

                        # Truncate word address to target width
                        if word_addr_width > target_word_addr_width:
                            index_var = f"((_ extract {target_word_addr_width-1} 0) {index_var})"
                        elif word_addr_width < target_word_addr_width:
                            extend_bits = target_word_addr_width - word_addr_width
                            index_var = f"((_ zero_extend {extend_bits}) {index_var})"

                        # Now scale to byte address
                        index_var = f"(concat {index_var} (_ bv0 {byte_offset_bits}))"
                    elif actual_index_width == addr_bits:
                        # Index width matches expected byte address width - already a byte address
                        # This handles SAIL's case where addr[11:0] is already a 12-bit byte address
                        # Just use it directly, no word->byte conversion needed
                        pass  # Keep index_var as-is
                    else:
                        # Index is already a word address (e.g., ILA's pc[31:2] which is 30 bits)
                        # Truncate word address to target width first
                        if actual_index_width > target_word_addr_width:
                            index_var = f"((_ extract {target_word_addr_width-1} 0) {index_var})"
                        elif actual_index_width < target_word_addr_width:
                            extend_bits = target_word_addr_width - actual_index_width
                            index_var = f"((_ zero_extend {extend_bits}) {index_var})"

                        # Now scale to byte address
                        index_var = f"(concat {index_var} (_ bv0 {byte_offset_bits}))"
                else:
                    # Already byte-addressed, just adjust width if needed
                    if actual_index_width > addr_bits:
                        index_var = f"((_ extract {addr_bits-1} 0) {index_var})"
                    elif actual_index_width < addr_bits:
                        extend_bits = addr_bits - actual_index_width
                        index_var = f"((_ zero_extend {extend_bits}) {index_var})"

                num_bytes = read_width // 8
                return self.generate_bytewise_read(array_var, index_var, num_bytes, addr_bits)
            # else: 8-bit read, fall through to normal select

        # Get the array variable (_in version since we're reading)
        array_var = self.get_node_var(array_node, "_in")

        # Get the index value
        index_var = self.get_value_var(index_node)

        # Check if this is word-addressed memory (has port_width or address_unit='word')
        port_width = array_node.data.get('port_width')
        address_unit = array_node.data.get('address_unit')
        is_word_addressed = port_width or (address_unit == 'word')

        if is_word_addressed:
            # Word-addressed memory: use word address (addr[31:2])
            actual_index_width = self.get_node_width(index_node)
            # Extract word address: addr[31:2]
            index_var = f"((_ extract {actual_index_width-1} 2) {index_var})"

            # Get expected index width from array dimensions first, then addr_bits
            # NOTE: If port_width is set, we reduced the array declaration by 2 bits,
            # so we must also reduce expected_index_width by 2 bits
            array_dims = array_node.data.get('dimensions') or []
            if len(array_dims) > 1:
                expected_index_width = array_dims[1][0] - array_dims[1][1] + 1
                # Subtract 2 if port_width set (array was declared with reduced width)
                if port_width and expected_index_width >= 2:
                    expected_index_width = expected_index_width - 2
            elif array_node.data.get('is_memory', False) and array_node.data.get('addr_bits'):
                # For ILA mem nodes with addr_bits set (already adjusted)
                expected_index_width = array_node.data.get('addr_bits')
            else:
                # Default: assume we already shifted by 2
                expected_index_width = actual_index_width - 2
        else:
            # Regular memory: use full address
            # Get expected index width from array dimensions
            array_dims = array_node.data.get('dimensions') or []
            expected_index_width = None

            if len(array_dims) > 1:
                expected_index_width = array_dims[1][0] - array_dims[1][1] + 1
            elif array_node.data.get('is_memory', False):
                # For mem nodes, use addr_bits
                expected_index_width = array_node.data.get('addr_bits')

        if expected_index_width:
            actual_index_width = self.get_node_width(index_node)
            current_index_width = actual_index_width - 2 if is_word_addressed else actual_index_width

            # Adjust index width if needed
            if current_index_width > expected_index_width:
                # Truncate to lower bits
                index_var = f"((_ extract {expected_index_width-1} 0) {index_var})"
            elif current_index_width < expected_index_width:
                # Zero-extend
                extend_bits = expected_index_width - current_index_width
                index_var = f"((_ zero_extend {extend_bits}) {index_var})"

        return f"(select {array_var} {index_var})"

    def generate_bytewise_read(self, array_var: str, base_addr: str, num_bytes: int, addr_width: int) -> str:
        """
        Generate a multi-byte read by concatenating consecutive byte reads.

        Args:
            array_var: The array variable to read from
            base_addr: Base byte address
            num_bytes: Number of bytes to read (2 or 4)
            addr_width: Width of address in bits

        Returns:
            SMT expression concatenating bytes into wider value
        """
        # Read bytes and concatenate them
        # For little-endian: byte0 is LSB, byte3 is MSB
        # Result = concat(byte3, concat(byte2, concat(byte1, byte0)))

        byte_reads = []
        for byte_idx in range(num_bytes):
            # Calculate byte address
            if byte_idx == 0:
                byte_addr = base_addr
            else:
                byte_addr = f"(bvadd {base_addr} (_ bv{byte_idx} {addr_width}))"

            # Read the byte
            byte_read = f"(select {array_var} {byte_addr})"
            byte_reads.append(byte_read)

        # Concatenate bytes (MSB to LSB for little-endian)
        result = byte_reads[0]
        for i in range(1, num_bytes):
            result = f"(concat {byte_reads[i]} {result})"

        return result

    def generate_bytewise_write(self, array_var: str, base_addr: str, value_var: str, num_bytes: int, addr_width: int) -> str:
        """
        Generate a series of byte-wise stores for a multi-byte write.

        Args:
            array_var: The array variable to write to
            base_addr: Base byte address
            value_var: Value to write (16-bit or 32-bit)
            num_bytes: Number of bytes to write (2 or 4)
            addr_width: Width of address in bits

        Returns:
            Nested store operations writing each byte
        """
        # Build nested stores from innermost (byte 0) to outermost (byte N-1)
        result = array_var
        for byte_idx in range(num_bytes):
            # Extract byte from value
            low_bit = byte_idx * 8
            high_bit = low_bit + 7
            byte_value = f"((_ extract {high_bit} {low_bit}) {value_var})"

            # Calculate byte address: base_addr + byte_idx
            # RISC-V uses byte addressing, so base_addr is already a byte address
            if byte_idx == 0:
                byte_addr = base_addr
            else:
                byte_addr = f"(bvadd {base_addr} (_ bv{byte_idx} {addr_width}))"

            result = f"(store {result} {byte_addr} {byte_value})"

        return result

    def convert_memory_write(self, node: Node) -> str:
        """
        Convert an ILA memory_write node to SMT store operation.

        ILA memory_write structure:
          - Position 0: array (base array to update)
          - Position 1: index (address)
          - Position 2: value (data to write)

        Returns: (store array index value) or nested byte-wise stores
        """
        # Find array, index, and value from incoming edges
        array_node = None
        index_node = None
        value_node = None

        for edge in self._sorted_edges(node.incoming_edges):
            position = edge.data.get('position')
            if position == 0:
                array_node = edge.source
            elif position == 1:
                index_node = edge.source
            elif position == 2:
                value_node = edge.source

        if not array_node or not index_node or not value_node:
            raise ValueError(f"Memory write {node.id} missing array ({array_node}), index ({index_node}), or value ({value_node})")

        # Check if this memory uses byte-wise representation
        is_bytewise = array_node.id in getattr(self, 'bytewise_memories', set())

        if is_bytewise:
            # Byte-wise memory - determine access width from the value being written
            value_width = self.get_node_width(value_node)

            if value_width > 8:
                # Multi-byte access - decompose into byte-wise stores
                array_var = self.get_node_var(array_node, "_in")
                index_var = self.get_value_var(index_node)
                value_var = self.get_value_var(value_node)

                # Get the expected byte address width
                # For word-addressed memories (data_width > 8), this includes the byte offset bits
                data_width = array_node.data.get('data_width') or array_node.data.get('bit_width', 8)
                # Use original_data_width if available (for byte-wise converted memories)
                original_data_width = array_node.data.get('original_data_width', data_width)
                addr_bits = array_node.data.get('addr_bits') or array_node.data.get('addr_width', 10)
                actual_index_width = self.get_node_width(index_node)

                # Convert word address to byte address if needed
                # If the original memory is word-addressed (original_data_width > 8), need to handle conversion
                if original_data_width > 8:
                    import math
                    byte_offset_bits = int(math.log2(original_data_width // 8))

                    # Determine if index is a byte address or word address
                    # ISA uses full 32-bit byte addresses even when indexing word-addressed memory
                    # ILA uses word addresses (e.g., 30-bit from PC[31:2])
                    target_word_addr_width = addr_bits - byte_offset_bits

                    if actual_index_width == 32:
                        # Index is exactly 32 bits - this is a byte address (e.g., ISA's address)
                        # Extract word address first: index[31:2], then truncate to target width
                        index_var = f"((_ extract 31 2) {index_var})"
                        word_addr_width = 30  # 32-bit byte addr -> 30-bit word addr

                        # Truncate word address to target width
                        if word_addr_width > target_word_addr_width:
                            index_var = f"((_ extract {target_word_addr_width-1} 0) {index_var})"
                        elif word_addr_width < target_word_addr_width:
                            extend_bits = target_word_addr_width - word_addr_width
                            index_var = f"((_ zero_extend {extend_bits}) {index_var})"

                        # Now scale to byte address
                        index_var = f"(concat {index_var} (_ bv0 {byte_offset_bits}))"
                    else:
                        # Index is already a word address (e.g., ILA's word index)
                        # Truncate word address to target width first
                        if actual_index_width > target_word_addr_width:
                            index_var = f"((_ extract {target_word_addr_width-1} 0) {index_var})"
                        elif actual_index_width < target_word_addr_width:
                            extend_bits = target_word_addr_width - actual_index_width
                            index_var = f"((_ zero_extend {extend_bits}) {index_var})"

                        # Now scale to byte address
                        index_var = f"(concat {index_var} (_ bv0 {byte_offset_bits}))"
                else:
                    # Already byte-addressed, just adjust width if needed
                    if actual_index_width > addr_bits:
                        index_var = f"((_ extract {addr_bits-1} 0) {index_var})"
                    elif actual_index_width < addr_bits:
                        extend_bits = addr_bits - actual_index_width
                        index_var = f"((_ zero_extend {extend_bits}) {index_var})"

                num_bytes = value_width // 8
                return self.generate_bytewise_write(array_var, index_var, value_var, num_bytes, addr_bits)
            # else: 8-bit write, fall through to normal store

        # Single-byte access or dimension-based array - use original logic
        array_var = self.get_node_var(array_node, "_in")
        index_var = self.get_value_var(index_node)
        value_var = self.get_value_var(value_node)

        # Adjust index width to match array's expected index type
        port_width = array_node.data.get('port_width')
        is_memory = array_node.data.get('is_memory', False)
        array_dims = array_node.data.get('dimensions') or []

        # Get expected index width
        expected_index_width = None
        if len(array_dims) > 1:
            expected_index_width = array_dims[1][0] - array_dims[1][1] + 1
            # Subtract 2 if port_width set (array was declared with reduced width)
            if port_width and expected_index_width >= 2 and is_memory:
                expected_index_width = expected_index_width - 2
        elif is_memory:
            # For byte-wise representation, use the SMT index width
            expected_index_width = array_node.data.get('addr_bits', 10)
            if access_width and access_width > 8:
                # Add byte offset bits
                if access_width == 16:
                    expected_index_width += 1
                elif access_width == 32:
                    expected_index_width += 2

        if expected_index_width:
            actual_index_width = self.get_node_width(index_node)

            if actual_index_width > expected_index_width:
                # Truncate to lower bits
                index_var = f"((_ extract {expected_index_width-1} 0) {index_var})"
            elif actual_index_width < expected_index_width:
                # Zero-extend
                extend_bits = expected_index_width - actual_index_width
                index_var = f"((_ zero_extend {extend_bits}) {index_var})"

        # Adjust value width to match array element width (always 8 for byte-wise)
        expected_value_width = 8  # Byte-wise representation
        actual_value_width = self.get_node_width(value_node)

        if actual_value_width < expected_value_width:
            # Zero-extend
            extend_bits = expected_value_width - actual_value_width
            value_var = f"((_ zero_extend {extend_bits}) {value_var})"
        elif actual_value_width > expected_value_width:
            # Truncate
            value_var = f"((_ extract {expected_value_width-1} 0) {value_var})"

        return f"(store {array_var} {index_var} {value_var})"

    def get_node_width(self, node: Node, visited: set = None) -> int:
        """Determine the bitvector width for a node."""
        # Check if node has explicit width FIRST, before cycle detection
        # This prevents incorrect default width returns for nodes with known widths
        if 'width' in node.data and node.data['width'] is not None:
            return node.data['width']

        # Check bit_width (for isa_state nodes)
        if 'bit_width' in node.data and node.data['bit_width'] is not None:
            return node.data['bit_width']

        # Check data_width (for multiplexers)
        if 'data_width' in node.data and node.data['data_width'] is not None:
            return node.data['data_width']

        # For array_access nodes, infer width from the base array's element width
        if node.data.get('type') == 'array_access':
            # Find the base array by looking for incoming edges of type 'array_index' or 'array_base'
            # that point to an isa_state node (the array itself)
            for edge in node.incoming_edges:
                if edge.data.get('type') in ('array_index', 'array_base'):
                    source = edge.source
                    source_type = source.data.get('type', '')
                    # Check if this is the array (isa_state) not the index
                    # Use startswith to match 'isa_state', 'isa_state mem', 'architectural_state', etc.
                    if source_type.startswith('isa_state') or source_type.startswith('architectural_state'):
                        # Return the array's bit_width (element width)
                        array_width = source.data.get('bit_width')
                        if array_width is not None:
                            return array_width

        # Cycle detection: track visited nodes to prevent infinite recursion
        # IMPORTANT: This check comes AFTER explicit width checks to avoid returning
        # default width (32) for nodes that have known widths set
        if visited is None:
            visited = set()
        if node.id in visited:
            # Return default width to break the cycle
            return 32
        visited.add(node.id)

        # Check bitslice in data
        if 'bitslice' in node.data:
            bitslice = node.data['bitslice']
            if bitslice:
                high, low = bitslice
                return high - low + 1

        # Check bit_slice expression
        if node.data.get('type') == 'bit_slice':
            expr = node.data.get('expression', {})
            if 'range' in expr:
                high, low = expr['range']
                return high - low + 1

        # Check dimensions (for memory/arrays)
        if 'dimensions' in node.data:
            dims = node.data['dimensions']
            if dims:
                high, low = dims[0]  # First dimension is bit width
                return high - low + 1

        # For repetition nodes: {count{value}}
        if node.data.get('type') == 'repetition':
            count = node.data.get('count', 1)
            for edge in self._sorted_edges(node.incoming_edges):
                if edge.data.get('type') == 'repetition_input':
                    source_width = self.get_node_width(edge.source, visited)
                    return count * source_width
            return count  # If no input, assume 1-bit source

        # For concatenation nodes: {part1, part2, ...}
        if node.data.get('type') in ['concatenation', 'concat']:
            total_width = 0
            for edge in self._sorted_edges(node.incoming_edges):
                if edge.data.get('type') in ['concatenation_input', 'concat_input']:
                    total_width += self.get_node_width(edge.source, visited)
            if total_width > 0:
                return total_width

        # For SAIL bitvector_concat operations
        if node.data.get('operator') == 'bitvector_concat':
            total_width = 0
            for edge in self._sorted_edges(node.incoming_edges):
                if edge.data.get('type') == 'operand':
                    total_width += self.get_node_width(edge.source, visited)
            if total_width > 0:
                return total_width

        # For var nodes, infer width from assignment source
        if node.data.get('type') == 'var':
            # Look for assignment edge (incoming edge of type 'assign' or 'dataflow')
            for edge in self._sorted_edges(node.incoming_edges):
                if edge.data.get('type') in ['assign', 'dataflow', 'assignment']:
                    source_width = self.get_node_width(edge.source, visited)
                    if source_width != 32:  # Only use if not default
                        return source_width

        # For literal nodes and sized_literal nodes, infer width from usage context
        if node.data.get('type') in ['literal', 'sized_literal']:
            # Check if this literal is used in a comparison or operation
            for edge in self._sorted_edges(node.outgoing_edges):
                if edge.data.get('type') == 'operand':
                    target_node = edge.target

                    # Special handling for bitvector_concat
                    if target_node.data.get('operator') == 'bitvector_concat':
                        # For concat, infer from the other operand
                        # Total width is sum of operands, so this_width = total - other_width
                        total_width = 32  # UTYPE creates 32-bit values
                        other_width = 0
                        for other_edge in self._sorted_edges(target_node.incoming_edges):
                            if other_edge.data.get('type') == 'operand' and other_edge.source != node:
                                other_width = self.get_node_width(other_edge.source, visited)
                                break
                        if other_width > 0:
                            this_width = total_width - other_width
                            if this_width > 0:
                                return this_width

                    # If used in an operation, check the other operand's width
                    if target_node.data.get('type') == 'operation':
                        # Find the other operand to this operation
                        for other_edge in self._sorted_edges(target_node.incoming_edges):
                            if other_edge.data.get('type') == 'operand' and other_edge.source != node:
                                # Use the other operand's width
                                other_width = self.get_node_width(other_edge.source, visited)
                                if other_width != 32:  # Only use if not default
                                    return other_width

        # For ternary operations, infer width from branches
        if node.data.get('type') in ['ternary_op', 'conditional']:
            # Find the true/false branches and return max width
            true_width = None
            false_width = None
            for edge in self._sorted_edges(node.incoming_edges):
                if edge.data.get('type') == 'ternary_true':
                    true_width = self.get_node_width(edge.source, visited)
                elif edge.data.get('type') == 'ternary_false':
                    false_width = self.get_node_width(edge.source, visited)
            # Return max of both branches (both should have same width in well-formed programs)
            if true_width is not None and false_width is not None:
                return max(true_width, false_width)
            elif true_width is not None:
                return true_width
            elif false_width is not None:
                return false_width

        # For ILA instruction nodes (decode signals), these are boolean mux selects
        if node.data.get('type') == 'instruction':
            return 1  # Boolean decode signal

        # For operations, try to infer from operands
        if node.data.get('type') == 'operation':
            expr = node.data.get('expression', {})
            operator = expr.get('operator') or node.data.get('operator')

            # SAIL bool_to_bits: converts boolean to 1-bit bitvector
            if operator == 'bool_to_bits':
                return 1

            # For binary operations (including shifts), result width depends on operator
            if expr.get('type') == 'binary_op':
                operator = expr.get('operator')

                # For comparison operations, result is always 1 bit (boolean)
                # Check this FIRST before falling back to operand width
                if operator in ['==', '!=', '<', '>', '<=', '>=',
                               '<_s', '<=_s', '>_s', '>=_s',
                               '<_u', '<=_u', '>_u', '>=_u',
                               '<s', '<=s', '>s', '>=s']:  # Also handle suffix without underscore
                    return 1

                # For arithmetic operations (+, -, *), result width is max of operands
                if operator in ['+', '-', '*']:
                    max_width = 0
                    for edge in self._sorted_edges(node.incoming_edges):
                        if edge.data.get('type') == 'operand':
                            operand_width = self.get_node_width(edge.source)
                            max_width = max(max_width, operand_width)
                    if max_width > 0:
                        return max_width

                # For other operations (shifts, bitwise), use left operand width
                # Find left operand by matching expression structure
                left_expr = expr.get('left', {})
                left_name = left_expr.get('name') if left_expr.get('type') == 'identifier' else None

                # Find the edge whose source matches the left operand
                for edge in self._sorted_edges(node.incoming_edges):
                    if edge.data.get('type') == 'operand':
                        # Check if this source is the left operand
                        source_name = edge.source.data.get('name', edge.source.id)
                        if left_name and (source_name == left_name or edge.source.id == left_name):
                            return self.get_node_width(edge.source)

                # If we couldn't match by name, use first operand as fallback
                operand_edges = [e for e in node.incoming_edges if e.data.get('type') == 'operand']
                if operand_edges:
                    return self.get_node_width(operand_edges[0].source)
            else:
                # For unary operations, use the operand width
                for edge in self._sorted_edges(node.incoming_edges):
                    if edge.data.get('type') == 'operand':
                        return self.get_node_width(edge.source)

        # For comparison operations, return 1 bit (boolean)
        if node.data.get('type') == 'operation':
            operator = node.data.get('operator', '')
            # Boolean comparison operators return 1-bit result
            if operator in ['==', '!=', '<', '>', '<=', '>=', '<_s', '>_s', '<=_s', '>=_s',
                           '<_u', '>_u', '<=_u', '>=_u', 'eq_vec', 'neq_vec']:
                return 1

        # For multiplexers, infer width from input edges
        if node.data.get('type') == 'multiplexer':
            for edge in self._sorted_edges(node.incoming_edges):
                edge_type = edge.data.get('type', '')
                # Check for mux_input or input0/input1 edges
                if edge_type.startswith('mux_input') or edge_type in ['input0', 'input1']:
                    input_width = self.get_node_width(edge.source)
                    # Return the first input's width (assume all inputs same width)
                    return input_width

        # Default to 32-bit
        return 32

    def convert_literal(self, node: Node) -> str:
        """Convert a literal node to SMT expression."""
        value = node.data.get('value', 0)
        width = self.get_node_width(node)

        # Handle different literal formats
        if isinstance(value, str):
            # Binary/hex literal
            if value.startswith('0b'):
                int_val = int(value[2:], 2)
            elif value.startswith('0x'):
                int_val = int(value[2:], 16)
            else:
                int_val = int(value)
        else:
            int_val = int(value)

        return f"(_ bv{int_val} {width})"

    def convert_sized_literal(self, node: Node) -> str:
        """Convert a sized literal node (e.g., 2'b0, 32'hFF) to SMT expression."""
        # Sized literals have format: <width>'b<value> or <width>'h<value>
        # The node ID usually contains this, e.g., "2'b0"
        node_id = node.id

        # Try to parse from node data first
        value = node.data.get('value')
        width = node.data.get('width') or node.data.get('bit_width')

        # If not in data, parse from ID
        if value is None and "'" in node_id:
            # Format: N'bXXXX or N'hXXXX
            parts = node_id.split("'")
            if len(parts) >= 2:
                try:
                    width = int(parts[0])
                    value_part = parts[1]
                    if value_part.startswith('b'):
                        value = int(value_part[1:], 2)
                    elif value_part.startswith('h'):
                        value = int(value_part[1:], 16)
                    elif value_part.startswith('d'):
                        value = int(value_part[1:])
                    else:
                        value = int(value_part)
                except:
                    value = 0
                    width = width or 32

        if value is None:
            value = 0
        if width is None:
            width = 32

        return f"(_ bv{value} {width})"

    def convert_ternary_op(self, node: Node) -> str:
        """Convert ternary operator (condition ? true_expr : false_expr) to SMT ite."""
        expr = node.data.get('expression', {})

        # Find condition, true_expr, and false_expr from incoming edges
        condition_node = None
        true_node = None
        false_node = None

        for edge in self._sorted_edges(node.incoming_edges):
            edge_type = edge.data.get('type')
            if edge_type == 'ternary_condition':
                condition_node = edge.source
            elif edge_type == 'ternary_true':
                true_node = edge.source
            elif edge_type == 'ternary_false':
                false_node = edge.source

        if not condition_node or not true_node or not false_node:
            raise ValueError(f"Ternary op {node.id} missing operands")

        condition_var = self.get_value_var(condition_node)

        # Convert 1-bit bitvector conditions to Bool for ite
        # Check if condition is a 1-bit bitvector (bit_slice, bit_access, etc.)
        # BUT if condition is already Bool (comparison, logical op), don't convert
        condition_type = condition_node.data.get('type')
        condition_op = condition_node.data.get('operator')
        is_bool_condition = (condition_type in ['comparison', 'logical_and', 'logical_or'] or
                            condition_op in ['==', '!=', '<', '>', '<=', '>=',
                                            '<_s', '<=_s', '>_s', '>=_s',
                                            '<_u', '<=_u', '>_u', '>=_u',
                                            '<s', '<=s', '>s', '>=s',
                                            'and', 'or', 'not'])

        if not is_bool_condition:
            # Convert BitVec to Bool for use in ite condition
            condition_width = self.get_node_width(condition_node)
            if condition_width == 1:
                # Convert BitVec(1) to Bool: (= condition_var #b1)
                condition_var = f"(= {condition_var} #b1)"
            elif condition_width and condition_width > 1:
                # Convert wider BitVec to Bool: (not (= condition_var (_ bv0 width)))
                # This checks if the value is non-zero (like C/C++ truthiness)
                condition_var = f"(not (= {condition_var} (_ bv0 {condition_width})))"

        # For ternary branches, use the ternary node's width (not the branch's inferred width)
        # This prevents literals from getting the wrong width from unrelated usage
        ternary_width = self.get_node_width(node)

        # Inline literals with the ternary's width, or get variable for non-literals
        if true_node.data.get('type') == 'literal':
            lit_value = true_node.data.get('value', 0)
            if isinstance(lit_value, str):
                if lit_value.startswith('0x'):
                    lit_value = int(lit_value[2:], 16)
                elif lit_value.startswith('0b'):
                    lit_value = int(lit_value[2:], 2)
                else:
                    lit_value = int(lit_value)
            else:
                lit_value = int(lit_value)
            true_var = f"(_ bv{lit_value} {ternary_width})"
        else:
            true_var = self.get_value_var(true_node)
            true_width = self.get_node_width(true_node)
            if true_width < ternary_width:
                # Check if this is a constant node with all bits set to 1
                # (common in sign-extension patterns)
                if true_node.data.get('type') == 'constant':
                    value_data = true_node.data.get('value', {})
                    if isinstance(value_data, dict):
                        value = value_data.get('v', 0)
                    else:
                        value = value_data
                    # Check if all bits are 1 in the source width
                    max_value = (1 << true_width) - 1  # All 1s for this width
                    if value == max_value:
                        # This is an all-1s constant for wide arithmetic - extend to all 1s
                        extended_value = (1 << ternary_width) - 1
                        true_var = f"(_ bv{extended_value} {ternary_width})"
                    else:
                        true_var = f"((_ zero_extend {ternary_width - true_width}) {true_var})"
                else:
                    true_var = f"((_ zero_extend {ternary_width - true_width}) {true_var})"

        if false_node.data.get('type') == 'literal':
            lit_value = false_node.data.get('value', 0)
            if isinstance(lit_value, str):
                if lit_value.startswith('0x'):
                    lit_value = int(lit_value[2:], 16)
                elif lit_value.startswith('0b'):
                    lit_value = int(lit_value[2:], 2)
                else:
                    lit_value = int(lit_value)
            else:
                lit_value = int(lit_value)
            false_var = f"(_ bv{lit_value} {ternary_width})"
        else:
            false_var = self.get_value_var(false_node)
            false_width = self.get_node_width(false_node)
            if false_width < ternary_width:
                # Check if this is a constant node with all bits set to 1
                # (common in sign-extension patterns)
                if false_node.data.get('type') == 'constant':
                    value_data = false_node.data.get('value', {})
                    if isinstance(value_data, dict):
                        value = value_data.get('v', 0)
                    else:
                        value = value_data
                    # Check if all bits are 1 in the source width
                    max_value = (1 << false_width) - 1  # All 1s for this width
                    if value == max_value:
                        # This is an all-1s constant for wide arithmetic - extend to all 1s
                        extended_value = (1 << ternary_width) - 1
                        false_var = f"(_ bv{extended_value} {ternary_width})"
                    else:
                        false_var = f"((_ zero_extend {ternary_width - false_width}) {false_var})"
                else:
                    false_var = f"((_ zero_extend {ternary_width - false_width}) {false_var})"

        return f"(ite {condition_var} {true_var} {false_var})"

    def convert_operation(self, node: Node) -> str:
        """Convert an operation node to SMT expression."""
        expr = node.data.get('expression', {})
        expr_type = expr.get('type')

        # Handle nodes that have operator directly in data (e.g., counter_increment from resource sharing)
        if expr_type is None and 'operator' in node.data:
            # Build a simple expression from operator
            operator = node.data.get('operator')
            # Don't assume type yet - will infer from operand count below
            expr = {'operator': operator}

        # Get operands, deduplicating by position
        # In merged graphs, we may have both shared and instruction-specific
        # versions of the same operand connected to an operation.
        # We prefer instruction-specific over shared.
        operands_by_position = {}  # position -> (edge, source_node)
        unnamed_position_counter = 0

        # Sort edges deterministically to avoid non-deterministic SMT generation
        for edge in self._sorted_edges(node.incoming_edges):
            edge_type = edge.data.get('type')
            # SAIL graphs use type=None for operand edges
            if edge_type == 'operand' or edge_type is None:
                position = edge.data.get('position')

                # If position is missing, assign a numbered position
                if position is None or position == 'unknown':
                    position = f'_pos_{unnamed_position_counter}'
                    unnamed_position_counter += 1

                source = edge.source

                # Prefer instruction-specific nodes over shared nodes
                if position not in operands_by_position:
                    operands_by_position[position] = (edge, source)
                else:
                    existing_edge, existing_source = operands_by_position[position]
                    existing_instr = existing_source.data.get('instruction', 'shared')
                    new_instr = source.data.get('instruction', 'shared')

                    # If new node is instruction-specific and existing is shared, replace
                    if new_instr not in ['shared', 'none', None] and existing_instr in ['shared', 'none', None]:
                        operands_by_position[position] = (edge, source)

        # Sort by position (left before right, then numbered positions)
        operands = []
        def sort_key(p):
            if p == 'left':
                return (0, 0)
            elif p == 'right':
                return (0, 1)
            elif isinstance(p, int):
                return (1, p)  # Numeric positions sorted by value
            elif isinstance(p, str):
                # Try to parse string as integer
                try:
                    return (1, int(p))
                except (ValueError, TypeError):
                    return (2, 0)  # Unknown positions last
            else:
                return (2, 0)  # Unknown positions last

        for position in sorted(operands_by_position.keys(), key=sort_key):
            edge, source = operands_by_position[position]
            operand_var = self.get_value_var(source)
            operands.append(operand_var)

        # Special handling for SAIL sign_extend and zero_extend operations
        # These have 2 incoming edges: target type (ignored) and source value
        operator = expr.get('operator')
        if operator in ['sign_extend', 'zero_extend']:
            # Filter operands to exclude the _temp target type node
            # The source is the one with a meaningful display_name (not "_temp")
            filtered_operands = []
            for pos, (edge, source) in operands_by_position.items():
                # Skip _temp nodes (SAIL type parameters)
                display_name = source.data.get('display_name', '')
                if display_name.startswith('_temp'):
                    continue
                filtered_operands.append(self.get_value_var(source))

            if len(filtered_operands) != 1:
                raise ValueError(f"{operator} operation should have 1 source operand after filtering, got {len(filtered_operands)}")

            source_var = filtered_operands[0]
            # Get source and target widths
            target_width = self.get_node_width(node)
            # Find the actual source node (not _temp)
            source_node = None
            for pos, (edge, src) in operands_by_position.items():
                display_name = src.data.get('display_name', '')
                if not display_name.startswith('_temp'):
                    source_node = src
                    break
            source_width = self.get_node_width(source_node) if source_node else 0
            extend_by = target_width - source_width

            if extend_by > 0:
                if operator == 'sign_extend':
                    return f"((_ sign_extend {extend_by}) {source_var})"
                else:  # zero_extend
                    return f"((_ zero_extend {extend_by}) {source_var})"
            else:
                return source_var

        # Handle bitvector_update(vector, index, value) - updates a single bit
        if operator == 'bitvector_update':
            if len(operands) != 3:
                raise ValueError(f"bitvector_update needs 3 operands, got {len(operands)}")

            # Get operands: vector, index, value
            vector_var = operands[0]
            index_var = operands[1]
            value_var = operands[2]

            # Get nodes for width info
            vector_node = operands_by_position.get(0, operands_by_position.get('_pos_0', (None, None)))[1]
            if not vector_node:
                vector_node = list(operands_by_position.values())[0][1]

            vector_width = self.get_node_width(vector_node)

            # For JALR: bitvector_update(addr, 0, 0) clears LSB
            # If index is constant 0 and value is constant 0, optimize to: (concat (extract[width-1:1] addr) #b0)
            # Otherwise, use general form with ite
            return f"(concat ((_ extract {vector_width-1} 1) {vector_var}) ((_ extract 0 0) {value_var}))"

        # Auto-detect expr_type from operand count if not already set
        if expr_type is None:
            if len(operands) == 1:
                expr_type = 'unary_op'
                expr['type'] = 'unary_op'
            elif len(operands) == 2:
                expr_type = 'binary_op'
                expr['type'] = 'binary_op'
            else:
                # Check if this is an n-ary OR/AND operation (from collision mux enable logic)
                operator = expr.get('operator') or node.data.get('operation')
                if operator in ['|', '||', 'or', '&', '&&', 'and']:
                    expr_type = 'nary_op'
                    expr['type'] = 'nary_op'
                else:
                    # Let it fall through to error handling below
                    expr_type = 'binary_op'  # Default for error message
                    expr['type'] = 'binary_op'

        # Handle n-ary operations (more than 2 operands)
        if expr_type == 'nary_op':
            operator = expr.get('operator') or node.data.get('operation')
            if operator in ['|', '||', 'or']:
                # Chain OR operations: (or a (or b (or c d)))
                result = operands[-1]
                for op in reversed(operands[:-1]):
                    result = f"(or {op} {result})"
                return result
            elif operator in ['&', '&&', 'and']:
                # Chain AND operations: (and a (and b (and c d)))
                result = operands[-1]
                for op in reversed(operands[:-1]):
                    result = f"(and {op} {result})"
                return result
            else:
                raise ValueError(f"Unsupported n-ary operator: {operator}")

        if expr_type == 'binary_op':
            operator = expr.get('operator') or node.data.get('operator') or node.data.get('operation')
            if len(operands) != 2:
                # Provide more debug info
                positions = list(operands_by_position.keys())
                raise ValueError(f"Binary operation needs 2 operands, got {len(operands)} "
                               f"(positions: {positions}, node: {node.id})")

            left, right = operands

            # Map operators to SMT
