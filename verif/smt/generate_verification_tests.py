# Template for README
README_TEMPLATE = '''# {isa_name} SMT Verification Tests

Auto-generated test suite for {isa_name} ISA verification.

## Test Files

- `test_{isa_dir}_smt_comprehensive.py` - Self-equivalence tests for all {num_instrs} instructions
- `test_{isa_dir}_merged_verification.py` - Merged processor verification

## Running Tests

```bash
# Run comprehensive self-equivalence tests
python3 test_{isa_dir}_smt_comprehensive.py

# Run merged processor verification
python3 test_{isa_dir}_merged_verification.py
```

## Instructions Covered

Total: {num_instrs} instructions

{instruction_list_formatted}

## Expected Results

- **Self-equivalence**: All instructions should pass (validates parser → SMT pipeline)
- **Merged processor**: Proves merged implementation is equivalent to standalone

## Generated

- Date: {date}
- Generator: generate_verification_tests.py
- ISA directory: {isa_dir}/
'''


def find_isa_files(isa_dir: str) -> list:
    """Find all .isa files in directory."""
    pattern = os.path.join(isa_dir, '*.isa')
    files = glob.glob(pattern)
    # Extract just the instruction names (without .isa)
    instructions = [Path(f).stem for f in files]
    instructions.sort()
    return instructions


def generate_comprehensive_test(isa_dir: str, output_dir: str, instructions: list, date: str):
    """Generate comprehensive self-equivalence test."""
    isa_name = Path(isa_dir).name.upper()

    test_content = TEST_TEMPLATE_COMPREHENSIVE.format(
        isa_name=isa_name,
        isa_dir=isa_dir,
        instruction_list=repr(instructions),
        date=date
    )

    output_file = os.path.join(
        output_dir,
        f'test_{Path(isa_dir).name}_smt_comprehensive.py'
    )

    with open(output_file, 'w') as f:
        f.write(test_content)

    # Make executable
    os.chmod(output_file, 0o755)

    print(f"  ✓ Generated: {output_file}")
    return output_file


def generate_merged_test(isa_dir: str, output_dir: str, instructions: list, date: str):
    """Generate merged processor verification test."""
    isa_name = Path(isa_dir).name.upper()

    # For initial merge test, use first 5-10 instructions
    # (or fewer if not many available)
    initial_instructions = instructions[:min(10, len(instructions))]

    test_content = TEST_TEMPLATE_MERGED.format(
        isa_name=isa_name,
        isa_dir=isa_dir,
        initial_instructions=repr(initial_instructions),
        date=date
    )

    output_file = os.path.join(
        output_dir,
        f'test_{Path(isa_dir).name}_merged_verification.py'
    )

    with open(output_file, 'w') as f:
        f.write(test_content)

    # Make executable
    os.chmod(output_file, 0o755)

    print(f"  ✓ Generated: {output_file}")
    return output_file


def generate_readme(isa_dir: str, output_dir: str, instructions: list, date: str):
    """Generate README for test directory."""
    isa_name = Path(isa_dir).name.upper()

    # Format instruction list
    instrs_formatted = []
    for i in range(0, len(instructions), 5):
        chunk = instructions[i:i+5]
        instrs_formatted.append("- " + ", ".join(chunk))
    instruction_list_formatted = "\n".join(instrs_formatted)

    readme_content = README_TEMPLATE.format(
        isa_name=isa_name,
        isa_dir=Path(isa_dir).name,
        num_instrs=len(instructions),
        instruction_list_formatted=instruction_list_formatted,
        date=date
    )

    output_file = os.path.join(output_dir, 'README.md')

    with open(output_file, 'w') as f:
        f.write(readme_content)

    print(f"  ✓ Generated: {output_file}")
    return output_file


def main():
    """Generate verification tests for ISA directory."""
    if len(sys.argv) < 2:
        print("Usage: python3 generate_verification_tests.py <isa_dir> [output_dir]")
        print()
        print("Examples:")
        print("  python3 generate_verification_tests.py mips32 verif/smt/mips32_generated")
        print("  python3 generate_verification_tests.py riscv32 verif/smt/riscv32")
        print("  python3 generate_verification_tests.py riscv_vector verif/smt/riscv_vector")
        return 1

    isa_dir = sys.argv[1]
    output_dir = sys.argv[2] if len(sys.argv) > 2 else f'verif/smt/{Path(isa_dir).name}_generated'

    if not os.path.isdir(isa_dir):
        print(f"Error: {isa_dir} is not a directory")
        return 1

    print("=" * 70)
    print("AUTOMATED TEST GENERATION")
    print("=" * 70)
    print()
    print(f"ISA directory: {isa_dir}")
    print(f"Output directory: {output_dir}")
    print()

    # Find ISA files
    print("Step 1: Scanning for .isa files...")
    instructions = find_isa_files(isa_dir)
    print(f"  Found {len(instructions)} instructions")

    if not instructions:
        print("  No .isa files found, aborting")
        return 1

    print()

    # Create output directory
    print("Step 2: Creating output directory...")
    os.makedirs(output_dir, exist_ok=True)
    print(f"  ✓ Created: {output_dir}")
    print()

    # Generate test files
    print("Step 3: Generating test files...")
    from datetime import datetime
    date = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    generated_files = []

    # Comprehensive test
    comp_file = generate_comprehensive_test(isa_dir, output_dir, instructions, date)
    generated_files.append(comp_file)

    # Merged test
    merged_file = generate_merged_test(isa_dir, output_dir, instructions, date)
    generated_files.append(merged_file)

    # README
    readme_file = generate_readme(isa_dir, output_dir, instructions, date)
    generated_files.append(readme_file)

    print()

    # Print summary
    print("=" * 70)
    print("GENERATION COMPLETE")
    print("=" * 70)
    print()
    print(f"Generated {len(generated_files)} files:")
    for f in generated_files:
        print(f"  - {f}")
    print()

    print("To run tests:")
    print(f"  python3 {comp_file}")
    print(f"  python3 {merged_file}")
    print()

    return 0


if __name__ == "__main__":
    sys.exit(main())
