# List of all MIPS32 instructions found in isa/mips32/
MIPS32_INSTRUCTIONS = ['add', 'addi', 'addiu', 'addu', 'and', 'andi', 'beq', 'bne', 'j', 'jal', 'jalr', 'jr', 'lb', 'lbu', 'lh', 'lhu', 'lui', 'lw', 'nor', 'or', 'ori', 'sb', 'sh', 'sll', 'sllv', 'slt', 'slti', 'sltiu', 'sltu', 'sra', 'srav', 'srl', 'srlv', 'sub', 'subu', 'sw', 'xor', 'xori']

def test_self_equivalence(instr_name: str) -> tuple:
    """Test that instruction is equivalent to itself."""
    print(f"  Testing {instr_name.upper()}...", end=' ', flush=True)

    isa_file = f'isa/mips32/{instr_name}.isa'

    try:
        graph = ResourceGraph.from_isa_file(isa_file)

        start = time.time()
        is_equiv, details = verify_optimization(
            graph, graph, isa_file_path=isa_file, solver='z3'
        )
        duration = time.time() - start

        if is_equiv:
            print(f"✓ PASS ({duration:.2f}s)")
            return True, duration
        else:
            print(f"✗ FAIL ({duration:.2f}s)")
            print(f"    Details: {details[:200]}")
            return False, duration

    except FileNotFoundError:
        print(f"⚠ SKIP (ISA file not found)")
        return None, 0.0
    except Exception as e:
        print(f"✗ ERROR: {e}")
        import traceback
        traceback.print_exc()
        return False, 0.0

