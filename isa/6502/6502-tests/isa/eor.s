; Test EOR (Exclusive OR) instruction - all addressing modes
; EOR: imm, zp, zp,X, abs, abs,X, abs,Y, (ind,X), (ind),Y

    * = $0400

start:
    ldx #0
    stx $00

; ============================================================================
; Test 1: EOR immediate - basic
; ============================================================================
test_1:
    ldx #1
    stx $00
    lda #$FF
    eor #$0F
    cmp #$F0
    beq test_2
    jmp fail

; ============================================================================
; Test 2: EOR with self = zero
; ============================================================================
test_2:
    ldx #2
    stx $00
    lda #$AA
    eor #$AA
    beq test_3          ; Result must be zero
    jmp fail

; ============================================================================
; Test 3: EOR with zero = unchanged
; ============================================================================
test_3:
    ldx #3
    stx $00
    lda #$55
    eor #$00
    cmp #$55
    beq test_4
    jmp fail

; ============================================================================
; Test 4: EOR with $FF = complement
; ============================================================================
test_4:
    ldx #4
    stx $00
    lda #$55
    eor #$FF
    cmp #$AA            ; ~$55 = $AA
    beq test_5
    jmp fail

; ============================================================================
; Test 5: EOR N flag
; ============================================================================
test_5:
    ldx #5
    stx $00
    lda #$00
    eor #$80
    bmi t5ok
    jmp fail
t5ok:
    cmp #$80
    beq test_6
    jmp fail

; ============================================================================
; Test 6: EOR zero page
; ============================================================================
test_6:
    ldx #6
    stx $00
    lda #$F0
    sta $10
    lda #$FF
    eor $10
    cmp #$0F
    beq test_7
    jmp fail

; ============================================================================
; Test 7: EOR zero page,X
; ============================================================================
test_7:
    ldx #7
    stx $00
    lda #$AA
    sta $18
    lda #$FF
    ldx #$08
    eor $10,x           ; Read from $18
    cmp #$55
    beq test_8
    jmp fail

; ============================================================================
; Test 8: EOR absolute
; ============================================================================
test_8:
    ldx #8
    stx $00
    lda #$33
    sta $0500
    lda #$FF
    eor $0500
    cmp #$CC            ; ~$33 = $CC
    beq test_9
    jmp fail

; ============================================================================
; Test 9: EOR absolute,X
; ============================================================================
test_9:
    ldx #9
    stx $00
    lda #$0F
    sta $0510
    lda #$FF
    ldx #$10
    eor $0500,x         ; Read from $0510
    cmp #$F0
    beq test_10
    jmp fail

; ============================================================================
; Test 10: EOR absolute,Y
; ============================================================================
test_10:
    ldx #10
    stx $00
    lda #$C3
    sta $0520
    lda #$FF
    ldy #$20
    eor $0500,y         ; Read from $0520
    cmp #$3C            ; ~$C3 = $3C
    beq test_11
    jmp fail

; ============================================================================
; Test 11: EOR double inversion = original
; ============================================================================
test_11:
    ldx #11
    stx $00
    lda #$42
    eor #$FF            ; First complement
    eor #$FF            ; Second complement
    cmp #$42            ; Back to original
    beq test_12
    jmp fail

; ============================================================================
; Test 12: EOR with bit patterns
; ============================================================================
test_12:
    ldx #12
    stx $00
    ; Test alternating bit patterns
    lda #$AA            ; 10101010
    eor #$55            ; 01010101
    cmp #$FF            ; Result should be all 1s
    beq pass
    jmp fail

; ============================================================================
; All tests passed
; ============================================================================
pass:
    jmp pass
fail:
    jmp fail
