; Test ORA (Logical Inclusive OR) instruction - all addressing modes
; ORA: imm, zp, zp,X, abs, abs,X, abs,Y, (ind,X), (ind),Y

    * = $0400

start:
    ldx #0
    stx $00

; ============================================================================
; Test 1: ORA immediate - basic
; ============================================================================
test_1:
    ldx #1
    stx $00
    lda #$0F
    ora #$F0
    cmp #$FF
    beq test_2
    jmp fail

; ============================================================================
; Test 2: ORA immediate - no change
; ============================================================================
test_2:
    ldx #2
    stx $00
    lda #$FF
    ora #$00
    cmp #$FF
    beq test_3
    jmp fail

; ============================================================================
; Test 3: ORA Z flag (result is zero only if both zero)
; ============================================================================
test_3:
    ldx #3
    stx $00
    lda #$00
    ora #$00
    beq test_4
    jmp fail

; ============================================================================
; Test 4: ORA N flag
; ============================================================================
test_4:
    ldx #4
    stx $00
    lda #$00
    ora #$80
    bmi t4ok
    jmp fail
t4ok:
    cmp #$80
    beq test_5
    jmp fail

; ============================================================================
; Test 5: ORA zero page
; ============================================================================
test_5:
    ldx #5
    stx $00
    lda #$AA
    sta $10
    lda #$55
    ora $10
    cmp #$FF
    beq test_6
    jmp fail

; ============================================================================
; Test 6: ORA zero page,X
; ============================================================================
test_6:
    ldx #6
    stx $00
    lda #$0F
    sta $18
    lda #$F0
    ldx #$08
    ora $10,x           ; Read from $18
    cmp #$FF
    beq test_7
    jmp fail

; ============================================================================
; Test 7: ORA absolute
; ============================================================================
test_7:
    ldx #7
    stx $00
    lda #$33
    sta $0500
    lda #$CC
    ora $0500
    cmp #$FF
    beq test_8
    jmp fail

; ============================================================================
; Test 8: ORA absolute,X
; ============================================================================
test_8:
    ldx #8
    stx $00
    lda #$0F
    sta $0510
    lda #$30
    ldx #$10
    ora $0500,x         ; Read from $0510
    cmp #$3F
    beq test_9
    jmp fail

; ============================================================================
; Test 9: ORA absolute,Y
; ============================================================================
test_9:
    ldx #9
    stx $00
    lda #$C0
    sta $0520
    lda #$03
    ldy #$20
    ora $0500,y         ; Read from $0520
    cmp #$C3
    beq test_10
    jmp fail

; ============================================================================
; Test 10: ORA (indirect,X)
; ============================================================================
test_10:
    ldx #10
    stx $00
    ; Set up pointer at $20: points to $0600
    lda #$00
    sta $20
    lda #$06
    sta $21
    ; Store test value
    lda #$F0
    sta $0600
    ; Test ORA
    lda #$0F
    ldx #$00
    ora ($20,x)
    cmp #$FF
    beq test_11
    jmp fail

; ============================================================================
; Test 11: ORA (indirect),Y
; ============================================================================
test_11:
    ldx #11
    stx $00
    ; Set up pointer at $30: points to $0700
    lda #$00
    sta $30
    lda #$07
    sta $31
    ; Store test value at $0705
    lda #$55
    sta $0705
    ; Test ORA
    lda #$AA
    ldy #$05
    ora ($30),y
    cmp #$FF
    beq test_12
    jmp fail

; ============================================================================
; Test 12: ORA chain - build up a value
; ============================================================================
test_12:
    ldx #12
    stx $00
    lda #$00
    ora #$01            ; bit 0
    ora #$02            ; bit 1
    ora #$04            ; bit 2
    ora #$08            ; bit 3
    cmp #$0F            ; should be $0F
    beq test_13
    jmp fail

; ============================================================================
; Test 13: ORA with self (idempotent)
; ============================================================================
test_13:
    ldx #13
    stx $00
    lda #$A5
    sta $40
    ora $40             ; A OR A = A
    cmp #$A5
    beq pass
    jmp fail

; ============================================================================
; All tests passed
; ============================================================================
pass:
    jmp pass
fail:
    jmp fail
