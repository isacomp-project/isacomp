; Test SBC (Subtract with Carry) instruction
; Note: SBC uses inverted carry (borrow = !C)

    * = $0400

start:
    ldx #0
    stx $00

; ============================================================================
; Test 1: SBC immediate - basic subtraction
; ============================================================================
test_1:
    ldx #1
    stx $00
    sec                 ; Set carry (no borrow)
    lda #$20
    sbc #$10            ; $20 - $10 = $10
    cmp #$10
    beq _ok0
    jmp fail
_ok0:

; ============================================================================
; Test 2: SBC with borrow
; ============================================================================
test_2:
    ldx #2
    stx $00
    clc                 ; Clear carry (borrow)
    lda #$20
    sbc #$10            ; $20 - $10 - 1 = $0F
    cmp #$0F
    beq _ok1
    jmp fail
_ok1:

; ============================================================================
; Test 3: SBC - borrow out (result negative)
; ============================================================================
test_3:
    ldx #3
    stx $00
    sec
    lda #$10
    sbc #$20            ; $10 - $20 = -$10 = $F0, borrow
    bcs fail            ; Carry should be clear (borrow occurred)
    cmp #$F0
    beq _ok2
    jmp fail
_ok2:

; ============================================================================
; Test 4: SBC - zero result
; ============================================================================
test_4:
    ldx #4
    stx $00
    sec
    lda #$50
    sbc #$50            ; $50 - $50 = 0
    bne fail            ; Z should be set
    bcc fail            ; No borrow, C should be set

; ============================================================================
; Test 5: SBC - N flag
; ============================================================================
test_5:
    ldx #5
    stx $00
    sec
    lda #$10
    sbc #$20            ; Result is negative
    bpl fail            ; N should be set

; ============================================================================
; Test 6: SBC - overflow positive - negative = negative
; ============================================================================
test_6:
    ldx #6
    stx $00
    sec
    lda #$50            ; Positive
    sbc #$B0            ; Negative (-80): $50 - (-$50) = $A0 (overflow)
    bvc fail            ; V should be set

; ============================================================================
; Test 7: SBC zero page
; ============================================================================
test_7:
    ldx #7
    stx $00
    lda #$10
    sta $10
    sec
    lda #$30
    sbc $10             ; $30 - $10 = $20
    cmp #$20
    beq _ok3
    jmp fail
_ok3:

; ============================================================================
; Test 8: SBC absolute
; ============================================================================
test_8:
    ldx #8
    stx $00
    lda #$05
    sta $0500
    sec
    lda #$15
    sbc $0500           ; $15 - $05 = $10
    cmp #$10
    beq _ok4
    jmp fail
_ok4:

; ============================================================================
; Test 9: SBC chain (RAW hazard on A and flags)
; ============================================================================
test_9:
    ldx #9
    stx $00
    sec
    lda #$50
    sbc #$10            ; $50 - $10 = $40, C=1
    sbc #$10            ; $40 - $10 = $30, C=1
    sbc #$10            ; $30 - $10 = $20, C=1
    cmp #$20
    beq _ok5
    jmp fail
_ok5:

; ============================================================================
; All tests passed
; ============================================================================
    jmp pass
pass:
    jmp pass
fail:
    jmp fail
