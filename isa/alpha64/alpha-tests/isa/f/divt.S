/*
 * Alpha DIVT (Divide T_floating) Test
 * Tests IEEE 754 double-precision division
 *
 * IEEE 754 double-precision hex values (hi, lo):
 *   1.0  = 0x3FF00000_00000000
 *   2.0  = 0x40000000_00000000
 *   3.0  = 0x40080000_00000000
 *   4.0  = 0x40100000_00000000
 *   0.5  = 0x3FE00000_00000000
 *   0.25 = 0x3FD00000_00000000
 *   1.5  = 0x3FF80000_00000000
 *   -0.5 = 0xBFE00000_00000000
 *   -1.0 = 0xBFF00000_00000000
 *   -2.0 = 0xC0000000_00000000
 *   0.0  = 0x00000000_00000000
 */

#include "../../env/test_macros.h"

ALPHA_TEST_BEGIN

    /*-------------------------------------------------------------
     * Basic arithmetic tests
     *-------------------------------------------------------------*/

    /* Test 2: 4.0 / 2.0 = 2.0 */
    TEST_FP_OP2_T(2, divt, 0x40000000, 0x00000000, 0x40100000, 0x00000000, 0x40000000, 0x00000000)

    /* Test 3: 2.0 / 1.0 = 2.0 */
    TEST_FP_OP2_T(3, divt, 0x40000000, 0x00000000, 0x40000000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 4: 1.0 / 1.0 = 1.0 */
    TEST_FP_OP2_T(4, divt, 0x3FF00000, 0x00000000, 0x3FF00000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 5: 1.0 / 2.0 = 0.5 */
    TEST_FP_OP2_T(5, divt, 0x3FE00000, 0x00000000, 0x3FF00000, 0x00000000, 0x40000000, 0x00000000)

    /* Test 6: 1.0 / 4.0 = 0.25 */
    TEST_FP_OP2_T(6, divt, 0x3FD00000, 0x00000000, 0x3FF00000, 0x00000000, 0x40100000, 0x00000000)

    /* Test 7: 0.0 / 1.0 = 0.0 */
    TEST_FP_OP2_T(7, divt, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 8: 0.0 / 2.0 = 0.0 */
    TEST_FP_OP2_T(8, divt, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x40000000, 0x00000000)

    /* Test 9: 2.0 / (-1.0) = -2.0 */
    TEST_FP_OP2_T(9, divt, 0xC0000000, 0x00000000, 0x40000000, 0x00000000, 0xBFF00000, 0x00000000)

    /* Test 10: (-2.0) / (-1.0) = 2.0 */
    TEST_FP_OP2_T(10, divt, 0x40000000, 0x00000000, 0xC0000000, 0x00000000, 0xBFF00000, 0x00000000)

    /* Test 11: (-1.0) / 2.0 = -0.5 */
    TEST_FP_OP2_T(11, divt, 0xBFE00000, 0x00000000, 0xBFF00000, 0x00000000, 0x40000000, 0x00000000)

    /* Test 12: 3.0 / 2.0 = 1.5 */
    TEST_FP_OP2_T(12, divt, 0x3FF80000, 0x00000000, 0x40080000, 0x00000000, 0x40000000, 0x00000000)

ALPHA_TEST_END
