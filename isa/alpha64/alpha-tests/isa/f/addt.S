/*
 * Alpha ADDT (Add T_floating) Test
 * Tests IEEE 754 double-precision addition
 *
 * IEEE 754 double-precision hex values (hi, lo):
 *   1.0  = 0x3FF00000_00000000
 *   2.0  = 0x40000000_00000000
 *   3.0  = 0x40080000_00000000
 *   0.5  = 0x3FE00000_00000000
 *   -1.0 = 0xBFF00000_00000000
 *   0.0  = 0x00000000_00000000
 */

#include "../../env/test_macros.h"

ALPHA_TEST_BEGIN

    /*-------------------------------------------------------------
     * Basic arithmetic tests
     *-------------------------------------------------------------*/

    /* Test 2: 1.0 + 1.0 = 2.0 */
    TEST_FP_OP2_T(2, addt, 0x40000000, 0x00000000, 0x3FF00000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 3: 1.0 + 2.0 = 3.0 */
    TEST_FP_OP2_T(3, addt, 0x40080000, 0x00000000, 0x3FF00000, 0x00000000, 0x40000000, 0x00000000)

    /* Test 4: 2.0 + 1.0 = 3.0 (commutativity) */
    TEST_FP_OP2_T(4, addt, 0x40080000, 0x00000000, 0x40000000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 5: 0.0 + 1.0 = 1.0 */
    TEST_FP_OP2_T(5, addt, 0x3FF00000, 0x00000000, 0x00000000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 6: 1.0 + 0.0 = 1.0 */
    TEST_FP_OP2_T(6, addt, 0x3FF00000, 0x00000000, 0x3FF00000, 0x00000000, 0x00000000, 0x00000000)

    /* Test 7: 0.0 + 0.0 = 0.0 */
    TEST_FP_OP2_T(7, addt, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x00000000)

    /* Test 8: 1.0 + (-1.0) = 0.0 */
    TEST_FP_OP2_T(8, addt, 0x00000000, 0x00000000, 0x3FF00000, 0x00000000, 0xBFF00000, 0x00000000)

    /* Test 9: (-1.0) + (-1.0) = -2.0 */
    TEST_FP_OP2_T(9, addt, 0xC0000000, 0x00000000, 0xBFF00000, 0x00000000, 0xBFF00000, 0x00000000)

    /* Test 10: 0.5 + 0.5 = 1.0 */
    TEST_FP_OP2_T(10, addt, 0x3FF00000, 0x00000000, 0x3FE00000, 0x00000000, 0x3FE00000, 0x00000000)

    /* Test 11: 2.0 + 0.5 = 2.5 */
    TEST_FP_OP2_T(11, addt, 0x40040000, 0x00000000, 0x40000000, 0x00000000, 0x3FE00000, 0x00000000)

ALPHA_TEST_END
