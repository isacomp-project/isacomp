/*
 * Alpha SUBT (Subtract T_floating) Test
 * Tests IEEE 754 double-precision subtraction
 *
 * IEEE 754 double-precision hex values (hi, lo):
 *   1.0  = 0x3FF00000_00000000
 *   2.0  = 0x40000000_00000000
 *   3.0  = 0x40080000_00000000
 *   0.5  = 0x3FE00000_00000000
 *   -1.0 = 0xBFF00000_00000000
 *   0.0  = 0x00000000_00000000
 */

#include "../../env/test_macros.h"

ALPHA_TEST_BEGIN

    /*-------------------------------------------------------------
     * Basic arithmetic tests
     *-------------------------------------------------------------*/

    /* Test 2: 2.0 - 1.0 = 1.0 */
    TEST_FP_OP2_T(2, subt, 0x3FF00000, 0x00000000, 0x40000000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 3: 3.0 - 1.0 = 2.0 */
    TEST_FP_OP2_T(3, subt, 0x40000000, 0x00000000, 0x40080000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 4: 3.0 - 2.0 = 1.0 */
    TEST_FP_OP2_T(4, subt, 0x3FF00000, 0x00000000, 0x40080000, 0x00000000, 0x40000000, 0x00000000)

    /* Test 5: 1.0 - 0.0 = 1.0 */
    TEST_FP_OP2_T(5, subt, 0x3FF00000, 0x00000000, 0x3FF00000, 0x00000000, 0x00000000, 0x00000000)

    /* Test 6: 0.0 - 1.0 = -1.0 */
    TEST_FP_OP2_T(6, subt, 0xBFF00000, 0x00000000, 0x00000000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 7: 0.0 - 0.0 = 0.0 */
    TEST_FP_OP2_T(7, subt, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x00000000)

    /* Test 8: 1.0 - 1.0 = 0.0 */
    TEST_FP_OP2_T(8, subt, 0x00000000, 0x00000000, 0x3FF00000, 0x00000000, 0x3FF00000, 0x00000000)

    /* Test 9: 1.0 - (-1.0) = 2.0 */
    TEST_FP_OP2_T(9, subt, 0x40000000, 0x00000000, 0x3FF00000, 0x00000000, 0xBFF00000, 0x00000000)

    /* Test 10: (-1.0) - (-1.0) = 0.0 */
    TEST_FP_OP2_T(10, subt, 0x00000000, 0x00000000, 0xBFF00000, 0x00000000, 0xBFF00000, 0x00000000)

    /* Test 11: 2.5 - 0.5 = 2.0 */
    TEST_FP_OP2_T(11, subt, 0x40000000, 0x00000000, 0x40040000, 0x00000000, 0x3FE00000, 0x00000000)

ALPHA_TEST_END
