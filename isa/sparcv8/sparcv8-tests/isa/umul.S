/* SPARCv8 UMUL instruction tests (unsigned multiply) */

#include "test_macros.h"

SPARCV8_TEST_CODE_BEGIN

  /*-------------------------------------------------------------
   * UMUL: Unsigned multiply, result low 32 bits in rd, high 32 in Y
   *-------------------------------------------------------------*/

  /*-------------------------------------------------------------
   * Test 2: Simple multiplication
   *-------------------------------------------------------------*/

  TEST_CASE( 2, %l0, 6, \
    set 2, %l1; \
    set 3, %l2; \
    umul %l1, %l2, %l0; \
  )

  /*-------------------------------------------------------------
   * Test 3: Multiply by zero
   *-------------------------------------------------------------*/

  TEST_CASE( 3, %l0, 0, \
    set 12345, %l1; \
    set 0, %l2; \
    umul %l1, %l2, %l0; \
  )

  /*-------------------------------------------------------------
   * Test 4: Multiply by one
   *-------------------------------------------------------------*/

  TEST_CASE( 4, %l0, 99, \
    set 99, %l1; \
    set 1, %l2; \
    umul %l1, %l2, %l0; \
  )

  /*-------------------------------------------------------------
   * Test 5: Large unsigned values (treated as positive)
   *-------------------------------------------------------------*/

  TEST_CASE( 5, %l0, 0xfffffffe, \
    set 0xffffffff, %l1; \
    set 2, %l2; \
    umul %l1, %l2, %l0; \
    /* 0xffffffff * 2 = 0x1_fffffffe, low 32 bits = 0xfffffffe */ \
  )

  /*-------------------------------------------------------------
   * Test 6: Larger multiplication
   *-------------------------------------------------------------*/

  TEST_CASE( 6, %l0, 1000000, \
    set 1000, %l1; \
    set 1000, %l2; \
    umul %l1, %l2, %l0; \
  )

  /*-------------------------------------------------------------
   * Test 7: UMUL with immediate operand
   *-------------------------------------------------------------*/

  TEST_CASE( 7, %l0, 50, \
    set 10, %l1; \
    umul %l1, 5, %l0; \
  )

  /*-------------------------------------------------------------
   * Test 8: 0x10000 * 0x10000 = 0x100000000, low 32 bits = 0
   *-------------------------------------------------------------*/

  TEST_CASE( 8, %l0, 0, \
    set 0x10000, %l1; \
    set 0x10000, %l2; \
    umul %l1, %l2, %l0; \
  )

  TEST_PASSFAIL

SPARCV8_TEST_CODE_END

SPARCV8_PASS
SPARCV8_FAIL

SPARCV8_DATA_BEGIN
  TEST_DATA
SPARCV8_DATA_END
