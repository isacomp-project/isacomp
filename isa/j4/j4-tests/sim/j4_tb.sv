// J4 (SuperH-4) Testbench for ISAComp
// Adapted for generated j4_basic module

module j4_tb;
    parameter TIMEOUT = 100000;

    reg clk = 0;
    reg reset = 1;

    // Reset value inputs (matching j4_basic module interface)
    wire [31:0] reset_branch_target_rd = 32'b0;
    wire reset_delay_slot = 1'b0;
    wire [31:0] reset_pc = 32'b0;
    wire [31:0] reset_pr = 32'b0;
    wire [31:0] reset_spc_rd = 32'b0;
    wire [31:0] reset_sr_rd = 32'h40000000;  // MD=1 (privileged mode)
    wire [31:0] reset_ssr_rd = 32'b0;
    wire reset_t_rd = 1'b0;
    wire [31:0] reset_vbr_rd = 32'b0;

    // Instantiate DUT (generated by ISAComp)
    j4_basic dut (
        .clk(clk),
        .reset(reset),
        .reset_branch_target_rd(reset_branch_target_rd),
        .reset_delay_slot(reset_delay_slot),
        .reset_pc(reset_pc),
        .reset_pr(reset_pr),
        .reset_spc_rd(reset_spc_rd),
        .reset_sr_rd(reset_sr_rd),
        .reset_ssr_rd(reset_ssr_rd),
        .reset_t_rd(reset_t_rd),
        .reset_vbr_rd(reset_vbr_rd)
    );

    // Pass/fail addresses from command line
    reg [31:0] pass_addr;
    reg [31:0] fail_addr;

    // Cycle counter
    integer cycles = 0;

    // Clock generation
    always #5 clk = ~clk;

    // Monitor PC
    wire [31:0] pc = dut.pc;

    initial begin
        // Get pass/fail addresses from command line
        if (!$value$plusargs("pass_addr=%h", pass_addr)) begin
            $display("ERROR: No pass_addr specified");
            $finish;
        end
        if (!$value$plusargs("fail_addr=%h", fail_addr)) begin
            $display("ERROR: No fail_addr specified");
            $finish;
        end

        // Load memory (16-bit memory)
        $readmemh("umem.hex", dut.umem);

        // Release reset after a few cycles
        #20 reset = 0;

        // Main simulation loop
        while (cycles < TIMEOUT) begin
            @(posedge clk);
            cycles = cycles + 1;

            // Debug output for first 20 cycles
            if (cycles <= 20) begin
                $display("Cycle %0d: PC=0x%h", cycles, pc);
            end else if (cycles % 1000 == 0) begin
                $display("Cycle %0d: PC=0x%h", cycles, pc);
            end

            if (pc == pass_addr) begin
                $display("TEST PASSED after %0d cycles", cycles);
                $finish;
            end

            if (pc == fail_addr) begin
                $display("TEST FAILED at cycle %0d", cycles);
                $finish;
            end
        end

        $display("TIMEOUT after %0d cycles (PC=0x%h)", cycles, pc);
        $finish;
    end

endmodule
